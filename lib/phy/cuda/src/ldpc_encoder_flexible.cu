/**
 * @brief Flexible LDPC encoding kernel
 * Works with any base graph and lifting size.
 * Uses one block per codeword, with Z threads per block.
 */
__global__ void ldpc_encode_flexible_kernel(
    const uint32_t* __restrict__ d_input,
    uint32_t* __restrict__ d_output,
    const int* __restrict__ d_row_ptr,
    const int8_t* __restrict__ d_col_idx,
    const int16_t* __restrict__ d_shifts,
    int Z,
    int Kb,
    int N,
    int M,
    int input_stride,
    int output_stride,
    int num_codewords,
    int base_graph,
    int lifting_set_idx
) {
    extern __shared__ uint32_t smem[];

    int cb_idx = blockIdx.x;
    if (cb_idx >= num_codewords) return;

    int z = threadIdx.x;
    if (z >= Z) return;

    // Calculate words needed per Z-column
    int words_per_Z = (Z + 31) / 32;

    // Pointers to input/output for this codeword
    const uint32_t* input = d_input + cb_idx * input_stride;
    uint32_t* output = d_output + cb_idx * output_stride;

    // Shared memory layout:
    // - code_buf: N * words_per_Z words for all variable nodes
    // - syndrome: M * words_per_Z words for parity check syndromes
    uint32_t* code_buf = smem;
    uint32_t* syndrome = code_buf + N * words_per_Z;

    // Clear all of code_buf and syndrome first
    for (int i = z; i < N * words_per_Z; i += Z) {
        code_buf[i] = 0;
    }
    for (int i = z; i < M * words_per_Z; i += Z) {
        syndrome[i] = 0;
    }

    __syncthreads();

    // Initialize code buffer with input (systematic bits)
    // Input bits are packed with MSB-first ordering within each byte
    // bit index = col * Z + z corresponds to:
    //   byte = bit_index / 8
    //   bit position within byte = 7 - (bit_index % 8)  [MSB-first]
    for (int col = 0; col < Kb && col < N; col++) {
        if (z < Z) {
            int input_bit_idx = col * Z + z;
            int input_word_idx = input_bit_idx / 32;
            // Convert to MSB-first bit position within the word
            int bit_in_word = input_bit_idx % 32;
            int byte_in_word = bit_in_word / 8;
            int bit_in_byte = 7 - (bit_in_word % 8);  // MSB-first within each byte
            int input_bit_pos = byte_in_word * 8 + bit_in_byte;

            if (input_word_idx < input_stride) {
                uint32_t word = input[input_word_idx];
                uint32_t bit = (word >> input_bit_pos) & 1;
                if (bit) {
                    atomicOr(&code_buf[col * words_per_Z + z / 32], 1u << (z % 32));
                }
            }
            // Bits beyond input are treated as 0 (filler or padding)
        }
    }

    __syncthreads();

    // Step 1: Compute syndromes for first 4 rows
    for (int row = 0; row < 4 && row < M; row++) {
        int row_start = d_row_ptr[row];
        int row_end = d_row_ptr[row + 1];

        int syn_bit = 0;
        for (int e = row_start; e < row_end; e++) {
            int col = d_col_idx[e];
            if (col >= Kb) continue;  // Only systematic columns

            int shift = d_shifts[e];
            if (shift < 0) continue;

            // Read bit with cyclic shift
            int src_z = (z + shift) % Z;
            int word_idx = col * words_per_Z + src_z / 32;
            int bit_pos = src_z % 32;
            int bit = (code_buf[word_idx] >> bit_pos) & 1;

            syn_bit ^= bit;
        }

        // Store syndrome bit
        int syn_word = row * words_per_Z + z / 32;
        int syn_pos = z % 32;
        if (syn_bit) {
            atomicOr(&syndrome[syn_word], 1u << syn_pos);
        }
    }

    __syncthreads();

    // Step 2 & 3: Compute parity bits p0, p1, p2, p3
    // The algorithm differs based on base graph and lifting set:
    //
    // BG1 i6: p0 uses shifted syndromes (by 105%Z), p1/p3 use p0[z]
    // BG1 other: p0 uses syndromes at z, p1/p3 use p0[(z+1)%Z]
    // BG2 i3/i7: p0 uses syndromes at z, p1/p3 use p0[(z+1)%Z]
    // BG2 other: p0 uses syndromes at (z-1), p1/p3 use p0[z]

    if (base_graph == 1) {
        // ===================== BG1 PARITY COMPUTATION =====================
        bool is_i6 = (lifting_set_idx == 6);

        // Compute p0 = XOR of syndromes (with optional shift for i6)
        int p0_bit = 0;
        if (is_i6) {
            // BG1 i6: read syndromes at shifted position
            int p0_syn_shift = 105 % Z;
            int src_z = (z - p0_syn_shift + Z) % Z;
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + src_z / 32;
                int syn_pos = src_z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        } else {
            // BG1 other: read syndromes at position z
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + z / 32;
                int syn_pos = z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        }

        // Store p0
        if (p0_bit) {
            atomicOr(&code_buf[Kb * words_per_Z + z / 32], 1u << (z % 32));
        }
        __syncthreads();

        // Read p0 at shifted position for p1/p3
        int p0_shift = is_i6 ? 0 : 1;  // i6: no shift, other: +1
        int p0_src_z = (z + p0_shift) % Z;
        int p0_word = Kb * words_per_Z + p0_src_z / 32;
        int p0_pos = p0_src_z % 32;
        int p0_shifted = (code_buf[p0_word] >> p0_pos) & 1;

        // Get syndromes at position z (aux[0], aux[2], aux[3] for p1, p2, p3)
        int syn0 = (syndrome[0 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn2 = (syndrome[2 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn3 = (syndrome[3 * words_per_Z + z / 32] >> (z % 32)) & 1;

        // p1 = aux0[k] ^ p0_shifted
        int p1_bit = syn0 ^ p0_shifted;
        if (p1_bit) {
            atomicOr(&code_buf[(Kb + 1) * words_per_Z + z / 32], 1u << (z % 32));
        }

        // p3 = aux3[k] ^ p0_shifted (compute p3 BEFORE p2, as srsRAN does)
        int p3_bit = syn3 ^ p0_shifted;
        if (p3_bit) {
            atomicOr(&code_buf[(Kb + 3) * words_per_Z + z / 32], 1u << (z % 32));
        }
        __syncthreads();

        // Read p3 at position z for p2
        int p3_z = (code_buf[(Kb + 3) * words_per_Z + z / 32] >> (z % 32)) & 1;

        // p2 = aux2[k] ^ p3[k] (per srsRAN BG1 formula)
        int p2_bit = syn2 ^ p3_z;
        if (p2_bit) {
            atomicOr(&code_buf[(Kb + 2) * words_per_Z + z / 32], 1u << (z % 32));
        }
    } else {
        // ===================== BG2 PARITY COMPUTATION =====================
        bool is_i3_i7 = (lifting_set_idx == 3 || lifting_set_idx == 7);

        // Compute p0 = XOR of syndromes
        int p0_bit = 0;
        if (is_i3_i7) {
            // BG2 i3/i7: read syndromes at position z
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + z / 32;
                int syn_pos = z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        } else {
            // BG2 other: read syndromes at position (z-1)
            int src_z = (z - 1 + Z) % Z;
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + src_z / 32;
                int syn_pos = src_z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        }

        // Store p0
        if (p0_bit) {
            atomicOr(&code_buf[Kb * words_per_Z + z / 32], 1u << (z % 32));
        }
        __syncthreads();

        // Read p0 at appropriate position for p1/p3
        int p0_src_z = is_i3_i7 ? ((z + 1) % Z) : z;  // i3/i7: +1 shift, other: no shift
        int p0_word = Kb * words_per_Z + p0_src_z / 32;
        int p0_pos = p0_src_z % 32;
        int p0_shifted = (code_buf[p0_word] >> p0_pos) & 1;

        // Get syndromes at position z
        int syn0 = (syndrome[0 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn1 = (syndrome[1 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn3 = (syndrome[3 * words_per_Z + z / 32] >> (z % 32)) & 1;

        // p1 = s0 ^ p0_shifted
        int p1_bit = syn0 ^ p0_shifted;
        if (p1_bit) {
            atomicOr(&code_buf[(Kb + 1) * words_per_Z + z / 32], 1u << (z % 32));
        }
        __syncthreads();

        // Read p1 at position z for p2
        int p1_z = (code_buf[(Kb + 1) * words_per_Z + z / 32] >> (z % 32)) & 1;

        // p2 = s1 ^ p1 (BG2: row 1 has p1, p2)
        int p2_bit = syn1 ^ p1_z;
        if (p2_bit) {
            atomicOr(&code_buf[(Kb + 2) * words_per_Z + z / 32], 1u << (z % 32));
        }
        __syncthreads();

        // p3 = s3 ^ p0_shifted (BG2: row 3 has p0, p3)
        int p3_bit = syn3 ^ p0_shifted;
        if (p3_bit) {
            atomicOr(&code_buf[(Kb + 3) * words_per_Z + z / 32], 1u << (z % 32));
        }
    }

    __syncthreads();

    // Step 4: Compute remaining parity bits (rows 4 to M-1)
    for (int row = 4; row < M; row++) {
        int row_start = d_row_ptr[row];
        int row_end = d_row_ptr[row + 1];

        int parity_bit = 0;
        int parity_col = -1;

        for (int e = row_start; e < row_end; e++) {
            int col = d_col_idx[e];
            int shift = d_shifts[e];
            if (shift < 0) continue;

            if (col >= Kb + 4) {
                // This is the parity column we're solving for
                parity_col = col;
            } else {
                // XOR with existing bit
                int src_z = (z + shift) % Z;
                int word_idx = col * words_per_Z + src_z / 32;
                int bit_pos = src_z % 32;
                parity_bit ^= (code_buf[word_idx] >> bit_pos) & 1;
            }
        }

        // Store parity bit
        if (parity_col >= 0 && parity_bit) {
            atomicOr(&code_buf[parity_col * words_per_Z + z / 32], 1u << (z % 32));
        }

        __syncthreads();
    }

    // Step 5: Copy codeword to output (all N columns)
    // Output uses MSB-first bit ordering within each byte to match srsRAN format
    for (int col = 0; col < N; col++) {
        int src_word = col * words_per_Z + z / 32;
        int src_bit = z % 32;
        int bit = (code_buf[src_word] >> src_bit) & 1;

        int dst_idx = col * Z + z;
        int dst_word = dst_idx / 32;
        // Convert to MSB-first bit position within each byte
        int bit_in_word = dst_idx % 32;
        int byte_in_word = bit_in_word / 8;
        int bit_in_byte = 7 - (bit_in_word % 8);  // MSB-first within byte
        int dst_bit = byte_in_word * 8 + bit_in_byte;

        if (dst_word < output_stride && bit) {
            atomicOr(&output[dst_word], 1u << dst_bit);
        }
    }
}

// ============================================================================
// Warp-Cooperative LDPC Encoding Kernel (Optimized - No atomics)
// ============================================================================

__device__ __forceinline__ int cyclic_add_fast(int z, int shift, int Z) {
    int result = z + shift;
    return (result >= Z) ? (result - Z) : result;
}

__device__ __forceinline__ int cyclic_sub_fast(int z, int shift, int Z) {
    int result = z - shift;
    return (result < 0) ? (result + Z) : result;
}

/**
 * @brief Warp-cooperative LDPC encoding kernel
 * Replaces atomicOr with __ballot_sync for 60x reduction in sync overhead.
 * Uses one block per codeword, with Z threads per block.
 */
template <int Z_FIXED>
__global__ void __launch_bounds__(384, 2)
ldpc_encode_warp_cooperative_kernel(
    const uint32_t* __restrict__ d_input,
    uint32_t* __restrict__ d_output,
    const int* __restrict__ d_row_ptr,
    const int8_t* __restrict__ d_col_idx,
    const int16_t* __restrict__ d_shifts,
    int Z_runtime,
    int Kb,
    int N,
    int M,
    int input_stride,
    int output_stride,
    int num_codewords,
    int base_graph,
    int lifting_set_idx
) {
    extern __shared__ uint32_t smem[];
    const int Z = (Z_FIXED > 0) ? Z_FIXED : Z_runtime;

    int cb_idx = blockIdx.x;
    if (cb_idx >= num_codewords) return;

    int z = threadIdx.x;
    if (z >= Z) return;

    // Warp-cooperative variables
    const int lane_id = z % 32;
    const int warp_id = z / 32;
    const int num_full_warps = Z / 32;
    const int partial_warp_size = Z % 32;
    const bool is_partial_warp = (warp_id == num_full_warps) && (partial_warp_size > 0);

    // Warp mask: full 0xFFFFFFFF for full warps, partial mask for last warp
    const uint32_t warp_mask = is_partial_warp ? ((1u << partial_warp_size) - 1) : 0xFFFFFFFF;

    // Calculate words needed per Z-column
    int words_per_Z = (Z + 31) / 32;

    // Pointers to input/output for this codeword
    const uint32_t* input = d_input + cb_idx * input_stride;
    uint32_t* output = d_output + cb_idx * output_stride;

    // Shared memory layout:
    // - code_buf: N * words_per_Z words for all variable nodes
    // - syndrome: M * words_per_Z words for parity check syndromes
    uint32_t* code_buf = smem;
    uint32_t* syndrome = code_buf + N * words_per_Z;

    // Clear all of code_buf and syndrome first
    for (int i = z; i < N * words_per_Z; i += Z) {
        code_buf[i] = 0;
    }
    for (int i = z; i < M * words_per_Z; i += Z) {
        syndrome[i] = 0;
    }

    __syncthreads();

    // Initialize code buffer with input (systematic bits)
    // Use __ballot_sync for warp-cooperative bit packing
    for (int col = 0; col < Kb && col < N; col++) {
        int bit = 0;
        if (z < Z) {
            int input_bit_idx = col * Z + z;
            int input_word_idx = input_bit_idx / 32;
            int bit_in_word = input_bit_idx % 32;
            int byte_in_word = bit_in_word / 8;
            int bit_in_byte = 7 - (bit_in_word % 8);
            int input_bit_pos = byte_in_word * 8 + bit_in_byte;

            if (input_word_idx < input_stride) {
                uint32_t word = input[input_word_idx];
                bit = (word >> input_bit_pos) & 1;
            }
        }

        // Warp-cooperative bit gathering
        uint32_t warp_bits = __ballot_sync(warp_mask, bit);
        if (lane_id == 0) {
            code_buf[col * words_per_Z + warp_id] = warp_bits;
        }
    }

    __syncthreads();

    // Step 1: Compute syndromes for first 4 rows
    for (int row = 0; row < 4 && row < M; row++) {
        int row_start = d_row_ptr[row];
        int row_end = d_row_ptr[row + 1];

        int syn_bit = 0;
        for (int e = row_start; e < row_end; e++) {
            int col = d_col_idx[e];
            if (col >= Kb) continue;

            int shift = d_shifts[e];
            if (shift < 0) continue;

            int src_z = cyclic_add_fast(z, shift, Z);
            int word_idx = col * words_per_Z + src_z / 32;
            int bit_pos = src_z % 32;
            int bit = (code_buf[word_idx] >> bit_pos) & 1;

            syn_bit ^= bit;
        }

        // Warp-cooperative syndrome storage
        uint32_t warp_bits = __ballot_sync(warp_mask, syn_bit);
        if (lane_id == 0) {
            syndrome[row * words_per_Z + warp_id] = warp_bits;
        }
    }

    __syncthreads();

    // Step 2 & 3: Compute parity bits p0, p1, p2, p3
    if (base_graph == 1) {
        // ===================== BG1 PARITY COMPUTATION =====================
        bool is_i6 = (lifting_set_idx == 6);

        // Compute p0 = XOR of syndromes
        int p0_bit = 0;
        if (is_i6) {
            int p0_syn_shift = 105 % Z;
            int src_z = cyclic_sub_fast(z, p0_syn_shift, Z);
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + src_z / 32;
                int syn_pos = src_z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        } else {
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + z / 32;
                int syn_pos = z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        }

        // Store p0 with warp-cooperative write
        {
            uint32_t warp_bits = __ballot_sync(warp_mask, p0_bit);
            if (lane_id == 0) {
                code_buf[Kb * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        // Read p0 at shifted position for p1/p3
        int p0_shift = is_i6 ? 0 : 1;
        int p0_src_z = cyclic_add_fast(z, p0_shift, Z);
        int p0_word = Kb * words_per_Z + p0_src_z / 32;
        int p0_pos = p0_src_z % 32;
        int p0_shifted = (code_buf[p0_word] >> p0_pos) & 1;

        int syn0 = (syndrome[0 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn2 = (syndrome[2 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn3 = (syndrome[3 * words_per_Z + z / 32] >> (z % 32)) & 1;

        // p1 = aux0[k] ^ p0_shifted
        int p1_bit = syn0 ^ p0_shifted;
        {
            uint32_t warp_bits = __ballot_sync(warp_mask, p1_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 1) * words_per_Z + warp_id] = warp_bits;
            }
        }

        // p3 = aux3[k] ^ p0_shifted
        int p3_bit = syn3 ^ p0_shifted;
        {
            uint32_t warp_bits = __ballot_sync(warp_mask, p3_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 3) * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        // Read p3 at position z for p2
        int p3_z = (code_buf[(Kb + 3) * words_per_Z + z / 32] >> (z % 32)) & 1;

        // p2 = aux2[k] ^ p3[k]
        int p2_bit = syn2 ^ p3_z;
        {
            uint32_t warp_bits = __ballot_sync(warp_mask, p2_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 2) * words_per_Z + warp_id] = warp_bits;
            }
        }
    } else {
        // ===================== BG2 PARITY COMPUTATION =====================
        bool is_i3_i7 = (lifting_set_idx == 3 || lifting_set_idx == 7);

        // Compute p0 = XOR of syndromes
        int p0_bit = 0;
        if (is_i3_i7) {
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + z / 32;
                int syn_pos = z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        } else {
            int src_z = cyclic_sub_fast(z, 1, Z);
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + src_z / 32;
                int syn_pos = src_z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        }

        // Store p0
        {
            uint32_t warp_bits = __ballot_sync(warp_mask, p0_bit);
            if (lane_id == 0) {
                code_buf[Kb * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        int p0_src_z = is_i3_i7 ? cyclic_add_fast(z, 1, Z) : z;
        int p0_word = Kb * words_per_Z + p0_src_z / 32;
        int p0_pos = p0_src_z % 32;
        int p0_shifted = (code_buf[p0_word] >> p0_pos) & 1;

        int syn0 = (syndrome[0 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn1 = (syndrome[1 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn3 = (syndrome[3 * words_per_Z + z / 32] >> (z % 32)) & 1;

        // p1 = s0 ^ p0_shifted
        int p1_bit = syn0 ^ p0_shifted;
        {
            uint32_t warp_bits = __ballot_sync(warp_mask, p1_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 1) * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        int p1_z = (code_buf[(Kb + 1) * words_per_Z + z / 32] >> (z % 32)) & 1;

        // p2 = s1 ^ p1
        int p2_bit = syn1 ^ p1_z;
        {
            uint32_t warp_bits = __ballot_sync(warp_mask, p2_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 2) * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        // p3 = s3 ^ p0_shifted
        int p3_bit = syn3 ^ p0_shifted;
        {
            uint32_t warp_bits = __ballot_sync(warp_mask, p3_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 3) * words_per_Z + warp_id] = warp_bits;
            }
        }
    }

    __syncthreads();

    // Step 4: Compute remaining parity bits (rows 4 to M-1)
    // KEY OPTIMIZATION: Extended parity rows only depend on systematic (cols 0-Kb-1)
    // and core parity (cols Kb to Kb+3). They DON'T depend on each other!
    // So we can compute ALL extended parity rows in parallel with just ONE syncthreads.
    for (int row = 4; row < M; row++) {
        int row_start = d_row_ptr[row];
        int row_end = d_row_ptr[row + 1];

        int parity_bit = 0;
        int parity_col = -1;

        for (int e = row_start; e < row_end; e++) {
            int col = d_col_idx[e];
            int shift = d_shifts[e];

            if (shift < 0) continue;

            if (col >= Kb + 4) {
                parity_col = col;
            } else {
                int src_z = cyclic_add_fast(z, shift, Z);
                int word_idx = col * words_per_Z + src_z / 32;
                int bit_pos = src_z % 32;
                int bit = (code_buf[word_idx] >> bit_pos) & 1;
                parity_bit ^= bit;
            }
        }

        // Store parity bit with warp-cooperative write (NO syncthreads needed between rows!)
        if (parity_col >= 0) {
            uint32_t warp_bits = __ballot_sync(warp_mask, parity_bit);
            if (lane_id == 0) {
                code_buf[parity_col * words_per_Z + warp_id] = warp_bits;
            }
        }
        // NO __syncthreads() here! Extended parity rows are independent
    }
    // Single syncthreads after ALL extended parity rows computed
    __syncthreads();

    // Step 5: Copy codeword to output
    // Use fast path for Z divisible by 32, slow path otherwise
    if ((Z % 32) == 0) {
        // Fast path: warp-cooperative writes with MSB-first byte reordering
        auto byte_reverse_bits = [](uint32_t x) -> uint32_t {
            x = ((x & 0x55555555u) << 1) | ((x >> 1) & 0x55555555u);
            x = ((x & 0x33333333u) << 2) | ((x >> 2) & 0x33333333u);
            x = ((x & 0x0F0F0F0Fu) << 4) | ((x >> 4) & 0x0F0F0F0Fu);
            return x;
        };

        for (int col = 0; col < N; col++) {
            // Read bit from shared memory
            int src_word = col * words_per_Z + warp_id;
            int bit = (code_buf[src_word] >> lane_id) & 1;

            // Gather bits from all lanes in warp
            uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, bit);

            // Apply MSB-first byte reordering
            warp_bits = byte_reverse_bits(warp_bits);

            // Lane 0 writes the entire word
            if (lane_id == 0) {
                int dst_word = col * words_per_Z + warp_id;
                if (dst_word < output_stride) {
                    output[dst_word] = warp_bits;
                }
            }
        }
    } else {
        // Non-32-aligned Z values, such as Z=240, still have a flat packed
        // output. Pack one output word per thread instead of using per-bit
        // atomics; this writes every output word exactly once.
        int total_code_bits = N * Z;
        int total_words = (total_code_bits + 31) / 32;
        for (int dst_word = z; dst_word < total_words && dst_word < output_stride; dst_word += Z) {
            int base_bit = dst_word * 32;
            uint32_t word = 0;

            #pragma unroll
            for (int b = 0; b < 32; ++b) {
                int bit_idx = base_bit + b;
                if (bit_idx >= total_code_bits) break;

                int col = bit_idx / Z;
                int src_z = bit_idx - col * Z;
                int src_word = col * words_per_Z + src_z / 32;
                int src_bit = src_z % 32;
                uint32_t bit = (code_buf[src_word] >> src_bit) & 1u;

                int dst_byte = b / 8;
                int dst_bit = dst_byte * 8 + (7 - (b % 8));
                word |= bit << dst_bit;
            }

            output[dst_word] = word;
        }
    }
}

/**
 * @brief Specialized Z=240 kernel that computes independent extension rows four at a time.
 *
 * Z=240 is a common small/medium single-layer PDSCH case. The generic warp-cooperative
 * kernel has only one or two CTAs for these transport blocks and walks the independent
 * extension parity rows serially. This variant keeps the same core parity algorithm, but
 * uses four padded Z-lanes per CTA for the independent extension rows.
 */
__global__ void __launch_bounds__(1024, 1)
ldpc_encode_warp_coop_z240_row4_kernel(
    const uint32_t* __restrict__ d_input,
    uint32_t* __restrict__ d_output,
    const int* __restrict__ d_row_ptr,
    const int8_t* __restrict__ d_col_idx,
    const int16_t* __restrict__ d_shifts,
    int Kb,
    int N,
    int M,
    int input_stride,
    int output_stride,
    int num_codewords,
    int base_graph,
    int lifting_set_idx
) {
    constexpr int Z = 240;
    constexpr int words_per_Z = 8;
    constexpr int padded_Z = 256;
    constexpr int rows_parallel = 4;

    extern __shared__ uint32_t smem[];

    int cb_idx = blockIdx.x;
    if (cb_idx >= num_codewords) return;

    int tid = threadIdx.x;
    int row_group = tid / padded_Z;
    int z = tid - row_group * padded_Z;
    bool active_z = z < Z;
    bool primary = (row_group == 0) && active_z;

    int lane_id = z & 31;
    int warp_id = z >> 5;
    uint32_t warp_mask = (warp_id == 7) ? 0x0000FFFFu : 0xFFFFFFFFu;

    const uint32_t* input = d_input + cb_idx * input_stride;
    uint32_t* output = d_output + cb_idx * output_stride;

    uint32_t* code_buf = smem;
    uint32_t* syndrome = code_buf + N * words_per_Z;

    for (int i = tid; i < N * words_per_Z; i += blockDim.x) {
        code_buf[i] = 0;
    }
    for (int i = tid; i < M * words_per_Z; i += blockDim.x) {
        syndrome[i] = 0;
    }
    __syncthreads();

    if (primary) {
        for (int col = 0; col < Kb && col < N; col++) {
            int input_bit_idx = col * Z + z;
            int input_word_idx = input_bit_idx / 32;
            int bit_in_word = input_bit_idx % 32;
            int byte_in_word = bit_in_word / 8;
            int bit_in_byte = 7 - (bit_in_word % 8);
            int input_bit_pos = byte_in_word * 8 + bit_in_byte;

            int bit = 0;
            if (input_word_idx < input_stride) {
                uint32_t word = input[input_word_idx];
                bit = (word >> input_bit_pos) & 1;
            }

            uint32_t warp_bits = __ballot_sync(warp_mask, bit);
            if (lane_id == 0) {
                code_buf[col * words_per_Z + warp_id] = warp_bits;
            }
        }
    }
    __syncthreads();

    if (primary) {
        for (int row = 0; row < 4 && row < M; row++) {
            int row_start = d_row_ptr[row];
            int row_end = d_row_ptr[row + 1];

            int syn_bit = 0;
            for (int e = row_start; e < row_end; e++) {
                int col = d_col_idx[e];
                if (col >= Kb) continue;

                int shift = d_shifts[e];
                if (shift < 0) continue;

                int src_z = cyclic_add_fast(z, shift, Z);
                int word_idx = col * words_per_Z + src_z / 32;
                int bit_pos = src_z % 32;
                syn_bit ^= (code_buf[word_idx] >> bit_pos) & 1;
            }

            uint32_t warp_bits = __ballot_sync(warp_mask, syn_bit);
            if (lane_id == 0) {
                syndrome[row * words_per_Z + warp_id] = warp_bits;
            }
        }
    }
    __syncthreads();

    if (base_graph == 1) {
        bool is_i6 = (lifting_set_idx == 6);

        if (primary) {
            int p0_bit = 0;
            if (is_i6) {
                int p0_syn_shift = 105 % Z;
                int src_z = cyclic_sub_fast(z, p0_syn_shift, Z);
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + src_z / 32;
                    int syn_pos = src_z % 32;
                    p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
                }
            } else {
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + z / 32;
                    int syn_pos = z % 32;
                    p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
                }
            }

            uint32_t warp_bits = __ballot_sync(warp_mask, p0_bit);
            if (lane_id == 0) {
                code_buf[Kb * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        if (primary) {
            int p0_shift = is_i6 ? 0 : 1;
            int p0_src_z = cyclic_add_fast(z, p0_shift, Z);
            int p0_word = Kb * words_per_Z + p0_src_z / 32;
            int p0_pos = p0_src_z % 32;
            int p0_shifted = (code_buf[p0_word] >> p0_pos) & 1;

            int syn0 = (syndrome[0 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int syn2 = (syndrome[2 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int syn3 = (syndrome[3 * words_per_Z + z / 32] >> (z % 32)) & 1;

            int p1_bit = syn0 ^ p0_shifted;
            uint32_t p1_bits = __ballot_sync(warp_mask, p1_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 1) * words_per_Z + warp_id] = p1_bits;
            }

            int p3_bit = syn3 ^ p0_shifted;
            uint32_t p3_bits = __ballot_sync(warp_mask, p3_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 3) * words_per_Z + warp_id] = p3_bits;
            }

            int p2_bit = syn2 ^ p3_bit;
            uint32_t p2_bits = __ballot_sync(warp_mask, p2_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 2) * words_per_Z + warp_id] = p2_bits;
            }
        }
    } else {
        bool is_i3_i7 = (lifting_set_idx == 3 || lifting_set_idx == 7);

        if (primary) {
            int p0_bit = 0;
            if (is_i3_i7) {
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + z / 32;
                    int syn_pos = z % 32;
                    p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
                }
            } else {
                int src_z = cyclic_sub_fast(z, 1, Z);
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + src_z / 32;
                    int syn_pos = src_z % 32;
                    p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
                }
            }

            uint32_t warp_bits = __ballot_sync(warp_mask, p0_bit);
            if (lane_id == 0) {
                code_buf[Kb * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        if (primary) {
            int p0_src_z = is_i3_i7 ? cyclic_add_fast(z, 1, Z) : z;
            int p0_word = Kb * words_per_Z + p0_src_z / 32;
            int p0_pos = p0_src_z % 32;
            int p0_shifted = (code_buf[p0_word] >> p0_pos) & 1;

            int syn0 = (syndrome[0 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int syn1 = (syndrome[1 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int syn3 = (syndrome[3 * words_per_Z + z / 32] >> (z % 32)) & 1;

            int p1_bit = syn0 ^ p0_shifted;
            uint32_t p1_bits = __ballot_sync(warp_mask, p1_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 1) * words_per_Z + warp_id] = p1_bits;
            }

            int p2_bit = syn1 ^ p1_bit;
            uint32_t p2_bits = __ballot_sync(warp_mask, p2_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 2) * words_per_Z + warp_id] = p2_bits;
            }

            int p3_bit = syn3 ^ p0_shifted;
            uint32_t p3_bits = __ballot_sync(warp_mask, p3_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 3) * words_per_Z + warp_id] = p3_bits;
            }
        }
    }
    __syncthreads();

    if (active_z && row_group < rows_parallel) {
        for (int row_base = 4; row_base < M; row_base += rows_parallel) {
            int row = row_base + row_group;
            if (row >= M) continue;

            int row_start = d_row_ptr[row];
            int row_end = d_row_ptr[row + 1];

            int parity_bit = 0;
            int parity_col = -1;

            for (int e = row_start; e < row_end; e++) {
                int col = d_col_idx[e];
                int shift = d_shifts[e];

                if (shift < 0) continue;

                if (col >= Kb + 4) {
                    parity_col = col;
                } else {
                    int src_z = cyclic_add_fast(z, shift, Z);
                    int word_idx = col * words_per_Z + src_z / 32;
                    int bit_pos = src_z % 32;
                    parity_bit ^= (code_buf[word_idx] >> bit_pos) & 1;
                }
            }

            if (parity_col >= 0) {
                uint32_t warp_bits = __ballot_sync(warp_mask, parity_bit);
                if (lane_id == 0) {
                    code_buf[parity_col * words_per_Z + warp_id] = warp_bits;
                }
            }
        }
    }
    __syncthreads();

    int total_code_bits = N * Z;
    int total_words = (total_code_bits + 31) / 32;
    for (int dst_word = tid; dst_word < total_words && dst_word < output_stride; dst_word += blockDim.x) {
        int base_bit = dst_word * 32;
        uint32_t word = 0;

        #pragma unroll
        for (int b = 0; b < 32; ++b) {
            int bit_idx = base_bit + b;
            if (bit_idx >= total_code_bits) break;

            int col = bit_idx / Z;
            int src_z = bit_idx - col * Z;
            int src_word = col * words_per_Z + src_z / 32;
            int src_bit = src_z % 32;
            uint32_t bit = (code_buf[src_word] >> src_bit) & 1u;

            int dst_byte = b / 8;
            int dst_bit = dst_byte * 8 + (7 - (b % 8));
            word |= bit << dst_bit;
        }

        output[dst_word] = word;
    }
}

// ============================================================================
// Fast Cyclic Index Helpers for Z=384 (avoid expensive modulo operations)
// ============================================================================

/**
 * @brief Fast cyclic index addition for Z=384 (avoids modulo operation)
 *
 * For Z=384, replacing (z + shift) % 384 with subtraction-based wrap
 * saves ~2 cycles per operation. In syndrome/parity computation loops,
 * this adds up to 5-8 µs savings per CB.
 */
__device__ __forceinline__ int cyclic_add_384(int z, int shift) {
    int result = z + shift;
    // Since z is in [0,383] and shift is in [0,383], result is in [0,766]
    // Only need one conditional subtraction
    return (result >= 384) ? (result - 384) : result;
}

__device__ __forceinline__ int cyclic_sub_384(int z, int shift) {
    int result = z - shift;
    // Since z is in [0,383] and shift is in [0,383], result is in [-383,383]
    // Only need one conditional addition
    return (result < 0) ? (result + 384) : result;
}

// ============================================================================
// Specialized Z=384 Warp-Cooperative Kernel (avoids modulo operations)
// ============================================================================

/**
 * @brief Specialized warp-cooperative LDPC kernel for Z=384
 *
 * Uses cyclic_add_384/cyclic_sub_384 helpers instead of modulo operations,
 * saving ~2 cycles per rotation. With 10-30 rotations per row and 42-68 rows,
 * this saves 5-8 µs per CB for small batches where warp-coop is used.
 *
 * PHASE 2 OPTIMIZATION: This kernel is selected automatically when Z=384 and
 * batch size is too small for multi-CB kernel (< 8 CBs).
 */
__global__ void __launch_bounds__(384, 2)
ldpc_encode_warp_coop_z384_kernel(
    const uint32_t* __restrict__ d_input,
    uint32_t* __restrict__ d_output,
    const int* __restrict__ d_row_ptr,
    const int8_t* __restrict__ d_col_idx,
    const int16_t* __restrict__ d_shifts,
    int Kb,
    int N,
    int M,
    int input_stride,
    int output_stride,
    int num_codewords,
    int base_graph,
    int lifting_set_idx
) {
    constexpr int Z = 384;
    constexpr int words_per_Z = 12;  // 384 / 32 = 12

    extern __shared__ uint32_t smem[];

    int cb_idx = blockIdx.x;
    if (cb_idx >= num_codewords) return;

    int z = threadIdx.x;
    if (z >= Z) return;

    // Warp-cooperative variables (Z=384 is exactly 12 warps, no partial)
    const int lane_id = z % 32;
    const int warp_id = z / 32;

    // Pointers to input/output for this codeword
    const uint32_t* input = d_input + cb_idx * input_stride;
    uint32_t* output = d_output + cb_idx * output_stride;

    // Shared memory layout
    uint32_t* code_buf = smem;
    uint32_t* syndrome = code_buf + N * words_per_Z;

    // Clear shared memory
    for (int i = z; i < N * words_per_Z; i += Z) {
        code_buf[i] = 0;
    }
    for (int i = z; i < M * words_per_Z; i += Z) {
        syndrome[i] = 0;
    }
    __syncthreads();

    // Initialize code buffer with input (systematic bits)
    for (int col = 0; col < Kb && col < N; col++) {
        int bit = 0;
        int input_bit_idx = col * Z + z;
        int input_word_idx = input_bit_idx / 32;
        int bit_in_word = input_bit_idx % 32;
        int byte_in_word = bit_in_word / 8;
        int bit_in_byte = 7 - (bit_in_word % 8);
        int input_bit_pos = byte_in_word * 8 + bit_in_byte;

        if (input_word_idx < input_stride) {
            uint32_t word = input[input_word_idx];
            bit = (word >> input_bit_pos) & 1;
        }

        uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, bit);
        if (lane_id == 0) {
            code_buf[col * words_per_Z + warp_id] = warp_bits;
        }
    }
    __syncthreads();

    // Step 1: Compute syndromes for first 4 rows (OPTIMIZED: use cyclic_add_384)
    for (int row = 0; row < 4 && row < M; row++) {
        int row_start = d_row_ptr[row];
        int row_end = d_row_ptr[row + 1];

        int syn_bit = 0;
        for (int e = row_start; e < row_end; e++) {
            int col = d_col_idx[e];
            if (col >= Kb) continue;

            int shift = d_shifts[e];
            if (shift < 0) continue;

            // OPTIMIZATION: Use fast cyclic add instead of modulo
            int src_z = cyclic_add_384(z, shift);
            int word_idx = col * words_per_Z + src_z / 32;
            int bit_pos = src_z % 32;
            int bit = (code_buf[word_idx] >> bit_pos) & 1;

            syn_bit ^= bit;
        }

        uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, syn_bit);
        if (lane_id == 0) {
            syndrome[row * words_per_Z + warp_id] = warp_bits;
        }
    }
    __syncthreads();

    // Step 2 & 3: Compute parity bits p0, p1, p2, p3
    if (base_graph == 1) {
        // BG1 parity computation
        bool is_i6 = (lifting_set_idx == 6);

        int p0_bit = 0;
        if (is_i6) {
            int p0_syn_shift = 105 % Z;  // 105 for BG1 i_LS=6
            int src_z = cyclic_sub_384(z, p0_syn_shift);
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + src_z / 32;
                int syn_pos = src_z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        } else {
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + z / 32;
                int syn_pos = z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        }

        {
            uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, p0_bit);
            if (lane_id == 0) {
                code_buf[Kb * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        int p0_shift = is_i6 ? 0 : 1;
        int p0_src_z = cyclic_add_384(z, p0_shift);
        int p0_word = Kb * words_per_Z + p0_src_z / 32;
        int p0_pos = p0_src_z % 32;
        int p0_shifted = (code_buf[p0_word] >> p0_pos) & 1;

        int syn0 = (syndrome[0 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn2 = (syndrome[2 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn3 = (syndrome[3 * words_per_Z + z / 32] >> (z % 32)) & 1;

        // p1 = aux0[k] ^ p0_shifted
        int p1_bit = syn0 ^ p0_shifted;
        {
            uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, p1_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 1) * words_per_Z + warp_id] = warp_bits;
            }
        }

        // p3 = aux3[k] ^ p0_shifted
        int p3_bit = syn3 ^ p0_shifted;
        {
            uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, p3_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 3) * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        int p3_z = (code_buf[(Kb + 3) * words_per_Z + z / 32] >> (z % 32)) & 1;
        int p2_bit = syn2 ^ p3_z;
        {
            uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, p2_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 2) * words_per_Z + warp_id] = warp_bits;
            }
        }
    } else {
        // BG2 parity computation
        bool is_i3_i7 = (lifting_set_idx == 3 || lifting_set_idx == 7);

        int p0_bit = 0;
        if (is_i3_i7) {
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + z / 32;
                int syn_pos = z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        } else {
            int src_z = cyclic_sub_384(z, 1);
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + src_z / 32;
                int syn_pos = src_z % 32;
                p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
            }
        }

        {
            uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, p0_bit);
            if (lane_id == 0) {
                code_buf[Kb * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        int p0_src_z = is_i3_i7 ? cyclic_add_384(z, 1) : z;
        int p0_word = Kb * words_per_Z + p0_src_z / 32;
        int p0_pos = p0_src_z % 32;
        int p0_shifted = (code_buf[p0_word] >> p0_pos) & 1;

        int syn0 = (syndrome[0 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn1 = (syndrome[1 * words_per_Z + z / 32] >> (z % 32)) & 1;
        int syn3 = (syndrome[3 * words_per_Z + z / 32] >> (z % 32)) & 1;

        int p1_bit = syn0 ^ p0_shifted;
        {
            uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, p1_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 1) * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        int p1_z = (code_buf[(Kb + 1) * words_per_Z + z / 32] >> (z % 32)) & 1;
        int p2_bit = syn1 ^ p1_z;
        {
            uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, p2_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 2) * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        int p3_bit = syn3 ^ p0_shifted;
        {
            uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, p3_bit);
            if (lane_id == 0) {
                code_buf[(Kb + 3) * words_per_Z + warp_id] = warp_bits;
            }
        }
    }
    __syncthreads();

    // Step 4: Compute remaining parity bits (rows 4 to M-1) - OPTIMIZED
    for (int row = 4; row < M; row++) {
        int row_start = d_row_ptr[row];
        int row_end = d_row_ptr[row + 1];

        int parity_bit = 0;
        int parity_col = -1;

        for (int e = row_start; e < row_end; e++) {
            int col = d_col_idx[e];
            int shift = d_shifts[e];

            if (shift < 0) continue;

            if (col >= Kb + 4) {
                parity_col = col;
            } else {
                // OPTIMIZATION: Use fast cyclic add
                int src_z = cyclic_add_384(z, shift);
                int word_idx = col * words_per_Z + src_z / 32;
                int bit_pos = src_z % 32;
                int bit = (code_buf[word_idx] >> bit_pos) & 1;
                parity_bit ^= bit;
            }
        }

        if (parity_col >= 0) {
            uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, parity_bit);
            if (lane_id == 0) {
                code_buf[parity_col * words_per_Z + warp_id] = warp_bits;
            }
        }
    }
    __syncthreads();

    // Step 5: Copy codeword to output (fast path - Z=384 is warp-aligned)
    auto byte_reverse_bits = [](uint32_t x) -> uint32_t {
        x = ((x & 0x55555555u) << 1) | ((x >> 1) & 0x55555555u);
        x = ((x & 0x33333333u) << 2) | ((x >> 2) & 0x33333333u);
        x = ((x & 0x0F0F0F0Fu) << 4) | ((x >> 4) & 0x0F0F0F0Fu);
        return x;
    };

    for (int col = 0; col < N; col++) {
        int src_word = col * words_per_Z + warp_id;
        int bit = (code_buf[src_word] >> lane_id) & 1;
        uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, bit);
        warp_bits = byte_reverse_bits(warp_bits);

        if (lane_id == 0) {
            int dst_word = col * words_per_Z + warp_id;
            if (dst_word < output_stride) {
                output[dst_word] = warp_bits;
            }
        }
    }
}

// ============================================================================
// Persistent Multi-CB Encoder Kernel (processes multiple CBs per block)
// ============================================================================

/**
 * @brief Persistent LDPC encoder - each block processes multiple CBs
 * This improves throughput by reducing kernel launch overhead and
 * better utilizing SM occupancy.
 */
__global__ void __launch_bounds__(384, 2)
ldpc_encode_persistent_kernel(
    const uint32_t* __restrict__ d_input,
    uint32_t* __restrict__ d_output,
    const int* __restrict__ d_row_ptr,
    const int8_t* __restrict__ d_col_idx,
    const int16_t* __restrict__ d_shifts,
    int Z,
    int Kb,
    int N,
    int M,
    int input_stride,
    int output_stride,
    int num_codewords,
    int base_graph,
    int lifting_set_idx
) {
    extern __shared__ uint32_t smem[];

    int z = threadIdx.x;
    if (z >= Z) return;

    // Warp-cooperative variables
    const int lane_id = z % 32;
    const int warp_id = z / 32;
    const int num_full_warps = Z / 32;
    const int partial_warp_size = Z % 32;
    const bool is_partial_warp = (warp_id == num_full_warps) && (partial_warp_size > 0);
    const uint32_t warp_mask = is_partial_warp ? ((1u << partial_warp_size) - 1) : 0xFFFFFFFF;

    int words_per_Z = (Z + 31) / 32;

    // Shared memory layout
    uint32_t* code_buf = smem;
    uint32_t* syndrome = code_buf + N * words_per_Z;

    // Process multiple CBs per block using persistent thread pattern
    for (int cb_idx = blockIdx.x; cb_idx < num_codewords; cb_idx += gridDim.x) {

        const uint32_t* input = d_input + cb_idx * input_stride;
        uint32_t* output = d_output + cb_idx * output_stride;

        // Clear shared memory
        for (int i = z; i < N * words_per_Z; i += Z) {
            code_buf[i] = 0;
        }
        for (int i = z; i < M * words_per_Z; i += Z) {
            syndrome[i] = 0;
        }
        __syncthreads();

        // Initialize code buffer with input (systematic bits)
        for (int col = 0; col < Kb && col < N; col++) {
            int bit = 0;
            if (z < Z) {
                int input_bit_idx = col * Z + z;
                int input_word_idx = input_bit_idx / 32;
                int bit_in_word = input_bit_idx % 32;
                int byte_in_word = bit_in_word / 8;
                int bit_in_byte = 7 - (bit_in_word % 8);
                int input_bit_pos = byte_in_word * 8 + bit_in_byte;

                if (input_word_idx < input_stride) {
                    uint32_t word = input[input_word_idx];
                    bit = (word >> input_bit_pos) & 1;
                }
            }

            uint32_t warp_bits = __ballot_sync(warp_mask, bit);
            if (lane_id == 0) {
                code_buf[col * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        // Step 1: Compute syndromes for first 4 rows
        for (int row = 0; row < 4 && row < M; row++) {
            int row_start = d_row_ptr[row];
            int row_end = d_row_ptr[row + 1];

            int syn_bit = 0;
            for (int e = row_start; e < row_end; e++) {
                int col = d_col_idx[e];
                if (col >= Kb) continue;

                int shift = d_shifts[e];
                if (shift < 0) continue;

                int src_z = (z + shift) % Z;
                int word_idx = col * words_per_Z + src_z / 32;
                int bit_pos = src_z % 32;
                int bit = (code_buf[word_idx] >> bit_pos) & 1;
                syn_bit ^= bit;
            }

            uint32_t warp_bits = __ballot_sync(warp_mask, syn_bit);
            if (lane_id == 0) {
                syndrome[row * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        // Step 2 & 3: Compute parity bits (BG1 or BG2)
        if (base_graph == 1) {
            bool is_i6 = (lifting_set_idx == 6);

            int p0_bit = 0;
            if (is_i6) {
                int p0_syn_shift = 105 % Z;
                int src_z = (z - p0_syn_shift + Z) % Z;
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + src_z / 32;
                    int syn_pos = src_z % 32;
                    p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
                }
            } else {
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + z / 32;
                    int syn_pos = z % 32;
                    p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
                }
            }

            {
                uint32_t warp_bits = __ballot_sync(warp_mask, p0_bit);
                if (lane_id == 0) code_buf[Kb * words_per_Z + warp_id] = warp_bits;
            }
            __syncthreads();

            int p0_shift = is_i6 ? 0 : 1;
            int p0_src_z = (z + p0_shift) % Z;
            int p0_word = Kb * words_per_Z + p0_src_z / 32;
            int p0_pos = p0_src_z % 32;
            int p0_shifted = (code_buf[p0_word] >> p0_pos) & 1;

            int syn0 = (syndrome[0 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int syn2 = (syndrome[2 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int syn3 = (syndrome[3 * words_per_Z + z / 32] >> (z % 32)) & 1;

            int p1_bit = syn0 ^ p0_shifted;
            {
                uint32_t warp_bits = __ballot_sync(warp_mask, p1_bit);
                if (lane_id == 0) code_buf[(Kb + 1) * words_per_Z + warp_id] = warp_bits;
            }

            int p3_bit = syn3 ^ p0_shifted;
            {
                uint32_t warp_bits = __ballot_sync(warp_mask, p3_bit);
                if (lane_id == 0) code_buf[(Kb + 3) * words_per_Z + warp_id] = warp_bits;
            }
            __syncthreads();

            int p3_z = (code_buf[(Kb + 3) * words_per_Z + z / 32] >> (z % 32)) & 1;
            int p2_bit = syn2 ^ p3_z;
            {
                uint32_t warp_bits = __ballot_sync(warp_mask, p2_bit);
                if (lane_id == 0) code_buf[(Kb + 2) * words_per_Z + warp_id] = warp_bits;
            }
        } else {
            // BG2 parity computation
            bool is_i3_i7 = (lifting_set_idx == 3 || lifting_set_idx == 7);

            int p0_bit = 0;
            if (is_i3_i7) {
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + z / 32;
                    int syn_pos = z % 32;
                    p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
                }
            } else {
                int src_z = (z - 1 + Z) % Z;
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + src_z / 32;
                    int syn_pos = src_z % 32;
                    p0_bit ^= (syndrome[syn_word] >> syn_pos) & 1;
                }
            }

            {
                uint32_t warp_bits = __ballot_sync(warp_mask, p0_bit);
                if (lane_id == 0) code_buf[Kb * words_per_Z + warp_id] = warp_bits;
            }
            __syncthreads();

            int p0_src_z = is_i3_i7 ? ((z + 1) % Z) : z;
            int p0_word = Kb * words_per_Z + p0_src_z / 32;
            int p0_pos = p0_src_z % 32;
            int p0_shifted = (code_buf[p0_word] >> p0_pos) & 1;

            int syn0 = (syndrome[0 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int syn1 = (syndrome[1 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int syn3 = (syndrome[3 * words_per_Z + z / 32] >> (z % 32)) & 1;

            int p1_bit = syn0 ^ p0_shifted;
            {
                uint32_t warp_bits = __ballot_sync(warp_mask, p1_bit);
                if (lane_id == 0) code_buf[(Kb + 1) * words_per_Z + warp_id] = warp_bits;
            }
            __syncthreads();

            int p1_z = (code_buf[(Kb + 1) * words_per_Z + z / 32] >> (z % 32)) & 1;
            int p2_bit = syn1 ^ p1_z;
            {
                uint32_t warp_bits = __ballot_sync(warp_mask, p2_bit);
                if (lane_id == 0) code_buf[(Kb + 2) * words_per_Z + warp_id] = warp_bits;
            }
            __syncthreads();

            int p3_bit = syn3 ^ p0_shifted;
            {
                uint32_t warp_bits = __ballot_sync(warp_mask, p3_bit);
                if (lane_id == 0) code_buf[(Kb + 3) * words_per_Z + warp_id] = warp_bits;
            }
        }
        __syncthreads();

        // Step 4: Compute remaining parity bits (rows 4 to M-1)
        for (int row = 4; row < M; row++) {
            int row_start = d_row_ptr[row];
            int row_end = d_row_ptr[row + 1];

            int parity_bit = 0;
            int parity_col = -1;

            for (int e = row_start; e < row_end; e++) {
                int col = d_col_idx[e];
                int shift = d_shifts[e];
                if (shift < 0) continue;

                if (col >= Kb + 4) {
                    parity_col = col;
                } else {
                    int src_z = (z + shift) % Z;
                    int word_idx = col * words_per_Z + src_z / 32;
                    int bit_pos = src_z % 32;
                    parity_bit ^= (code_buf[word_idx] >> bit_pos) & 1;
                }
            }

            if (parity_col >= 0) {
                uint32_t warp_bits = __ballot_sync(warp_mask, parity_bit);
                if (lane_id == 0) {
                    code_buf[parity_col * words_per_Z + warp_id] = warp_bits;
                }
            }
            __syncthreads();
        }

        // Step 5: Copy codeword to output
        for (int col = 0; col < N; col++) {
            int src_word = col * words_per_Z + z / 32;
            int src_bit = z % 32;
            int bit = (code_buf[src_word] >> src_bit) & 1;

            int dst_idx = col * Z + z;
            int dst_word = dst_idx / 32;
            int bit_in_word = dst_idx % 32;
            int byte_in_word = bit_in_word / 8;
            int bit_in_byte = 7 - (bit_in_word % 8);
            int dst_bit = byte_in_word * 8 + bit_in_byte;

            if (dst_word < output_stride && bit) {
                atomicOr(&output[dst_word], 1u << dst_bit);
            }
        }

        // Sync before processing next CB
        __syncthreads();
    }
}

// ============================================================================
// Funnel Shift Helper for Cyclic Bit Rotation (Aerial SDK technique)
// Must be outside extern "C" for template support
// ============================================================================

/**
 * @brief Get rotated 32-bit word using funnel shift
 *
 * For Z=384 (12 words), this efficiently performs cyclic rotation.
 * __funnelshift_r(lo, hi, shift) = (hi:lo >> shift)[31:0]
 */
template<int NUM_WORDS>
__device__ __forceinline__ uint32_t funnel_rotated_word(
    const uint32_t* col_data,  // Pointer to column's words
    int warp_id,               // Which word we want (0 to NUM_WORDS-1)
    int shift                  // Bit shift amount (0 to Z-1)
) {
    int word_shift = shift / 32;
    int bit_shift = shift % 32;

    // Source word indices with wrap-around
    int lo_idx = (warp_id + word_shift) % NUM_WORDS;
    int hi_idx = (lo_idx + 1) % NUM_WORDS;

    uint32_t lo = col_data[lo_idx];
    uint32_t hi = col_data[hi_idx];

    // Funnel shift: combines hi:lo and extracts 32 bits at bit_shift
    return __funnelshift_r(lo, hi, bit_shift);
}

// Specialization for Z=384 (12 words) - avoid modulo with subtraction
template<>
__device__ __forceinline__ uint32_t funnel_rotated_word<12>(
    const uint32_t* col_data,
    int warp_id,
    int shift
) {
    int word_shift = shift / 32;
    int bit_shift = shift % 32;

    // For Z=384: warp_id is 0-11, word_shift is 0-11
    // lo_idx = warp_id + word_shift, max = 22, so subtract 12 if >= 12
    int lo_idx = warp_id + word_shift;
    if (lo_idx >= 12) lo_idx -= 12;

    int hi_idx = lo_idx + 1;
    if (hi_idx >= 12) hi_idx = 0;

    uint32_t lo = col_data[lo_idx];
    uint32_t hi = col_data[hi_idx];

    return __funnelshift_r(lo, hi, bit_shift);
}

