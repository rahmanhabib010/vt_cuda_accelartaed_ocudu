/**
 * @brief Compute shift value for a given Z from reference shift
 */
static inline int compute_shift(int shift_ref, int Z, int Z_ref) {
    // 3GPP TS 38.212: The actual shift for lifting size Z is V_{i,j} mod Z
    // where V_{i,j} are the shift values from the base graph table.
    // No scaling is needed - the shifts are stored per lifting set and we just take modulo.
    (void)Z_ref;
    if (shift_ref == 0) return 0;
    if (shift_ref < 0) return -1;  // No connection
    return shift_ref % Z;
}

/**
 * @brief Get reference Z for a given lifting set index
 */
static inline int get_Z_ref(int lifting_set_idx) {
    static const int z_refs[] = {256, 384, 320, 224, 288, 352, 208, 240};
    return z_refs[lifting_set_idx];
}

/**
 * @brief Get lifting set index from Z value
 */
static int get_lifting_set_idx(int Z) {
    static const int set_bases[8] = {2, 3, 5, 7, 9, 11, 13, 15};
    for (int i = 0; i < 8; i++) {
        int base = set_bases[i];
        if (Z % base == 0) {
            int ratio = Z / base;
            if (ratio > 0 && (ratio & (ratio - 1)) == 0) {
                return i;
            }
        }
    }
    return -1;
}

static bool ldpc_encoder_env_flag_enabled(const char* name, bool default_value)
{
    const char* value = std::getenv(name);
    if (value == nullptr) {
        return default_value;
    }
    return (std::strcmp(value, "1") == 0) || (std::strcmp(value, "true") == 0) ||
           (std::strcmp(value, "on") == 0) || (std::strcmp(value, "yes") == 0);
}

