extern "C" {

nr_ldpc_status_t ldpc_encoder_create(ldpc_encoder_handle_t* handle) {
    FlexibleLdpcEncoder* enc = new (std::nothrow) FlexibleLdpcEncoder;
    if (!enc) return NR_LDPC_ERROR_ALLOC_FAILED;

    memset(enc, 0, sizeof(*enc));

    // Initialize cache to "not cached" state
    enc->cached_base_graph = -1;
    enc->cached_lifting_set_idx = -1;
    enc->cached_Z = -1;

    // Query GPU properties for platform-adaptive kernel selection
    int device;
    cudaGetDevice(&device);
    cudaDeviceProp prop;
    cudaGetDeviceProperties(&prop, device);
    enc->sm_count = prop.multiProcessorCount;

    // Launch bounds specify max 3 blocks per SM for our optimized kernels
    enc->max_blocks_per_sm = 3;

    *handle = reinterpret_cast<ldpc_encoder_handle_t>(enc);
    return NR_LDPC_SUCCESS;
}

nr_ldpc_status_t ldpc_encoder_configure(ldpc_encoder_handle_t handle, const nr_ldpc_config_t* cfg) {
    FlexibleLdpcEncoder* enc = reinterpret_cast<FlexibleLdpcEncoder*>(handle);
    if (!enc || !cfg) return NR_LDPC_ERROR_INVALID_CONFIG;

    enc->config = *cfg;
    enc->base_graph = cfg->base_graph;
    enc->Z = cfg->lifting_size;

    // Validate Z and store lifting set index
    enc->lifting_set_idx = get_lifting_set_idx(enc->Z);
    if (enc->lifting_set_idx < 0) {
        fprintf(stderr, "ERROR: Invalid lifting size Z=%d\n", enc->Z);
        return NR_LDPC_ERROR_INVALID_Z;
    }
    int lifting_set_idx = enc->lifting_set_idx;

    // Set parameters based on base graph
    if (enc->base_graph == 1) {
        enc->Kb = BG1_KB;
        enc->N = BG1_COLS;
        enc->M = BG1_ROWS;
        enc->nnz = BG1_NNZ;
    } else if (enc->base_graph == 2) {
        enc->Kb = BG2_KB;
        enc->N = BG2_COLS;
        enc->M = BG2_ROWS;
        enc->nnz = 197;  // Reduced for BG2 encoding
    } else {
        fprintf(stderr, "ERROR: Invalid base graph %d\n", enc->base_graph);
        return NR_LDPC_ERROR_INVALID_BG;
    }

    enc->input_bits = enc->Kb * enc->Z;
    enc->input_words = (enc->input_bits + 31) / 32;
    enc->output_bits = enc->N * enc->Z;
    // Encoder uses FLAT bit packing: bit i at word i/32, bit position i%32
    enc->output_words = (enc->output_bits + 31) / 32;

    // OPTIMIZATION: Skip reallocation if graph parameters haven't changed
    // The device buffers (row_ptr, col_idx, shifts) depend on base_graph, lifting_set_idx, AND Z
    // Shifts are computed as shift_ref % Z, so different Z values need different cached shifts
    // This eliminates ~300µs of cudaMalloc/cudaFree/cudaMemcpy overhead per slot when Z is unchanged
    if (enc->cached_base_graph == enc->base_graph &&
        enc->cached_lifting_set_idx == lifting_set_idx &&
        enc->cached_Z == enc->Z) {
        // Graph structure is unchanged - reuse existing device buffers
        return NR_LDPC_SUCCESS;
    }

    // Graph parameters changed - need to reallocate and copy
    const int* row_ptr = (enc->base_graph == 1) ? bg1_row_ptr : bg2_row_ptr;
    const int8_t* col_idx = (enc->base_graph == 1) ? bg1_col : bg2_col;

    // Select the correct shift table based on lifting set index
    const int16_t* shifts_ref;
    if (enc->base_graph == 1) {
        if (lifting_set_idx < 0 || lifting_set_idx >= BG1_NUM_LIFTING_SETS) {
            fprintf(stderr, "ERROR: Invalid lifting set index %d for BG1 encoder\n", lifting_set_idx);
            return NR_LDPC_ERROR_INVALID_CONFIG;
        }
        shifts_ref = bg1_shifts[lifting_set_idx];
    } else {
        if (lifting_set_idx < 0 || lifting_set_idx >= BG2_NUM_LIFTING_SETS) {
            fprintf(stderr, "ERROR: Invalid lifting set index %d for BG2 encoder\n", lifting_set_idx);
            return NR_LDPC_ERROR_INVALID_CONFIG;
        }
        shifts_ref = bg2_shifts[lifting_set_idx];
    }

    int num_rows = enc->M + 1;

    // Free existing buffers
    if (enc->d_row_ptr) cudaFree(enc->d_row_ptr);
    if (enc->d_col_idx) cudaFree(enc->d_col_idx);
    if (enc->d_shifts) cudaFree(enc->d_shifts);

    cudaMalloc(&enc->d_row_ptr, num_rows * sizeof(int));
    cudaMalloc(&enc->d_col_idx, enc->nnz * sizeof(int8_t));
    cudaMalloc(&enc->d_shifts, enc->nnz * sizeof(int16_t));

    cudaMemcpy(enc->d_row_ptr, row_ptr, num_rows * sizeof(int), cudaMemcpyHostToDevice);
    cudaMemcpy(enc->d_col_idx, col_idx, enc->nnz * sizeof(int8_t), cudaMemcpyHostToDevice);

    // Compute scaled shifts for this Z using lifting-set-specific Z_ref
    int16_t* scaled_shifts = new int16_t[enc->nnz];
    int Z_ref = get_Z_ref(lifting_set_idx);
    for (int i = 0; i < enc->nnz; i++) {
        scaled_shifts[i] = compute_shift(shifts_ref[i], enc->Z, Z_ref);
    }

    cudaMemcpy(enc->d_shifts, scaled_shifts, enc->nnz * sizeof(int16_t), cudaMemcpyHostToDevice);
    delete[] scaled_shifts;

    // Update cache
    enc->cached_base_graph = enc->base_graph;
    enc->cached_lifting_set_idx = lifting_set_idx;
    enc->cached_Z = enc->Z;

    return NR_LDPC_SUCCESS;
}

// ============================================================================
// Multi-CB Per Block Encoder Kernel (4× ILP)
// ============================================================================

/**
 * @brief Multi-CB LDPC encoder - processes 4 CBs per block using ILP
 *
 * Each thread handles 4 independent CBs, hiding memory latency through
 * instruction-level parallelism. This is the highest-throughput kernel.
 *
 * Shared memory layout: 4 interleaved code buffers and syndrome arrays
 * Thread assignment: thread z handles bit position z for all 4 CBs
 */
#define MULTI_CB_COUNT 4

__global__ void __launch_bounds__(384, 2)
ldpc_encode_multi_cb_kernel(
    const uint32_t* __restrict__ d_input,
    uint32_t* __restrict__ d_output,
    const int* __restrict__ d_row_ptr,
    const int8_t* __restrict__ d_col_idx,
    const int16_t* __restrict__ d_shifts,
    int Z,
    int Kb,
    int N,
    int M,
    int input_stride,
    int output_stride,
    int num_codewords,
    int base_graph,
    int lifting_set_idx
) {
    extern __shared__ uint32_t smem[];

    // Each block processes MULTI_CB_COUNT (4) CBs
    const int cb_base = blockIdx.x * MULTI_CB_COUNT;

    // How many valid CBs this block processes (handle tail)
    const int valid_cbs = min(MULTI_CB_COUNT, num_codewords - cb_base);
    if (valid_cbs <= 0) return;

    const int z = threadIdx.x;
    if (z >= Z) return;

    // Warp-cooperative variables
    const int lane_id = z % 32;
    const int warp_id = z / 32;
    const int num_full_warps = Z / 32;
    const int partial_warp_size = Z % 32;
    const bool is_partial_warp = (warp_id == num_full_warps) && (partial_warp_size > 0);
    const uint32_t warp_mask = is_partial_warp ? ((1u << partial_warp_size) - 1) : 0xFFFFFFFF;

    const int words_per_Z = (Z + 31) / 32;
    const int code_buf_size = N * words_per_Z;
    const int syndrome_size = M * words_per_Z;

    // Shared memory layout: 4 code buffers followed by 4 syndrome arrays
    // code_buf[cb][col * words_per_Z + warp_id]
    // syndrome[cb][row * words_per_Z + warp_id]
    uint32_t* code_buf[MULTI_CB_COUNT];
    uint32_t* syndrome[MULTI_CB_COUNT];

    for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
        code_buf[cb] = smem + cb * code_buf_size;
        syndrome[cb] = smem + MULTI_CB_COUNT * code_buf_size + cb * syndrome_size;
    }

    // Input/output pointers for each CB
    const uint32_t* input[MULTI_CB_COUNT];
    uint32_t* output[MULTI_CB_COUNT];
    for (int cb = 0; cb < valid_cbs; cb++) {
        input[cb] = d_input + (cb_base + cb) * input_stride;
        output[cb] = d_output + (cb_base + cb) * output_stride;
    }

    // Clear shared memory (all 4 code buffers and syndrome arrays)
    for (int i = z; i < MULTI_CB_COUNT * code_buf_size; i += Z) {
        smem[i] = 0;
    }
    for (int i = z; i < MULTI_CB_COUNT * syndrome_size; i += Z) {
        smem[MULTI_CB_COUNT * code_buf_size + i] = 0;
    }
    __syncthreads();

    // =========================================================================
    // Step 0: Load systematic bits for all 4 CBs using ILP
    // =========================================================================
    for (int col = 0; col < Kb && col < N; col++) {
        int bits[MULTI_CB_COUNT] = {0, 0, 0, 0};

        // Load all 4 CBs in parallel (ILP)
        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                int input_bit_idx = col * Z + z;
                int input_word_idx = input_bit_idx / 32;
                int bit_in_word = input_bit_idx % 32;
                int byte_in_word = bit_in_word / 8;
                int bit_in_byte = 7 - (bit_in_word % 8);
                int input_bit_pos = byte_in_word * 8 + bit_in_byte;

                if (input_word_idx < input_stride) {
                    uint32_t word = input[cb][input_word_idx];
                    bits[cb] = (word >> input_bit_pos) & 1;
                }
            }
        }

        // Warp-cooperative storage for all 4 CBs
        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                uint32_t warp_bits = __ballot_sync(warp_mask, bits[cb]);
                if (lane_id == 0) {
                    code_buf[cb][col * words_per_Z + warp_id] = warp_bits;
                }
            }
        }
    }
    __syncthreads();

    // =========================================================================
    // Step 1: Compute syndromes for first 4 rows (all 4 CBs with ILP)
    // =========================================================================
    for (int row = 0; row < 4 && row < M; row++) {
        int row_start = d_row_ptr[row];
        int row_end = d_row_ptr[row + 1];

        int syn_bits[MULTI_CB_COUNT] = {0, 0, 0, 0};

        for (int e = row_start; e < row_end; e++) {
            int col = d_col_idx[e];
            if (col >= Kb) continue;

            int shift = d_shifts[e];
            if (shift < 0) continue;

            int src_z = (z + shift) % Z;
            int word_idx = col * words_per_Z + src_z / 32;
            int bit_pos = src_z % 32;

            #pragma unroll
            for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                if (cb < valid_cbs) {
                    int bit = (code_buf[cb][word_idx] >> bit_pos) & 1;
                    syn_bits[cb] ^= bit;
                }
            }
        }

        // Store syndromes for all 4 CBs
        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                uint32_t warp_bits = __ballot_sync(warp_mask, syn_bits[cb]);
                if (lane_id == 0) {
                    syndrome[cb][row * words_per_Z + warp_id] = warp_bits;
                }
            }
        }
    }
    __syncthreads();

    // =========================================================================
    // Step 2 & 3: Compute parity bits p0-p3 (BG1 only for now, most common case)
    // =========================================================================
    if (base_graph == 1) {
        bool is_i6 = (lifting_set_idx == 6);

        // Compute p0 for all 4 CBs
        int p0_bits[MULTI_CB_COUNT] = {0, 0, 0, 0};

        if (is_i6) {
            int p0_syn_shift = 105 % Z;
            int src_z = (z - p0_syn_shift + Z) % Z;
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + src_z / 32;
                int syn_pos = src_z % 32;
                #pragma unroll
                for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                    if (cb < valid_cbs) {
                        p0_bits[cb] ^= (syndrome[cb][syn_word] >> syn_pos) & 1;
                    }
                }
            }
        } else {
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + z / 32;
                int syn_pos = z % 32;
                #pragma unroll
                for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                    if (cb < valid_cbs) {
                        p0_bits[cb] ^= (syndrome[cb][syn_word] >> syn_pos) & 1;
                    }
                }
            }
        }

        // Store p0 for all 4 CBs
        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                uint32_t warp_bits = __ballot_sync(warp_mask, p0_bits[cb]);
                if (lane_id == 0) {
                    code_buf[cb][Kb * words_per_Z + warp_id] = warp_bits;
                }
            }
        }
        __syncthreads();

        // Read p0, compute p1, p2, p3 for all 4 CBs
        int p0_shift = is_i6 ? 0 : 1;
        int p0_src_z = (z + p0_shift) % Z;
        int p0_word_idx = Kb * words_per_Z + p0_src_z / 32;
        int p0_pos = p0_src_z % 32;

        int p0_shifted[MULTI_CB_COUNT];
        int syn0[MULTI_CB_COUNT], syn2[MULTI_CB_COUNT], syn3[MULTI_CB_COUNT];

        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                p0_shifted[cb] = (code_buf[cb][p0_word_idx] >> p0_pos) & 1;
                syn0[cb] = (syndrome[cb][0 * words_per_Z + z / 32] >> (z % 32)) & 1;
                syn2[cb] = (syndrome[cb][2 * words_per_Z + z / 32] >> (z % 32)) & 1;
                syn3[cb] = (syndrome[cb][3 * words_per_Z + z / 32] >> (z % 32)) & 1;
            }
        }

        // p1 = syn0 ^ p0_shifted
        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                int p1_bit = syn0[cb] ^ p0_shifted[cb];
                uint32_t warp_bits = __ballot_sync(warp_mask, p1_bit);
                if (lane_id == 0) {
                    code_buf[cb][(Kb + 1) * words_per_Z + warp_id] = warp_bits;
                }
            }
        }

        // p3 = syn3 ^ p0_shifted
        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                int p3_bit = syn3[cb] ^ p0_shifted[cb];
                uint32_t warp_bits = __ballot_sync(warp_mask, p3_bit);
                if (lane_id == 0) {
                    code_buf[cb][(Kb + 3) * words_per_Z + warp_id] = warp_bits;
                }
            }
        }
        __syncthreads();

        // p2 = syn2 ^ p3
        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                int p3_z = (code_buf[cb][(Kb + 3) * words_per_Z + z / 32] >> (z % 32)) & 1;
                int p2_bit = syn2[cb] ^ p3_z;
                uint32_t warp_bits = __ballot_sync(warp_mask, p2_bit);
                if (lane_id == 0) {
                    code_buf[cb][(Kb + 2) * words_per_Z + warp_id] = warp_bits;
                }
            }
        }
    } else {
        // BG2: Fall back to processing one CB at a time (rare case)
        // For full optimization, would need to duplicate BG2 logic with ILP
        bool is_i3_i7 = (lifting_set_idx == 3 || lifting_set_idx == 7);

        for (int cb = 0; cb < valid_cbs; cb++) {
            int p0_bit = 0;
            if (is_i3_i7) {
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + z / 32;
                    int syn_pos = z % 32;
                    p0_bit ^= (syndrome[cb][syn_word] >> syn_pos) & 1;
                }
            } else {
                int src_z = (z - 1 + Z) % Z;
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + src_z / 32;
                    int syn_pos = src_z % 32;
                    p0_bit ^= (syndrome[cb][syn_word] >> syn_pos) & 1;
                }
            }

            uint32_t warp_bits = __ballot_sync(warp_mask, p0_bit);
            if (lane_id == 0) code_buf[cb][Kb * words_per_Z + warp_id] = warp_bits;
            __syncthreads();

            int p0_src_z = is_i3_i7 ? ((z + 1) % Z) : z;
            int p0_word = Kb * words_per_Z + p0_src_z / 32;
            int p0_pos = p0_src_z % 32;
            int p0_shifted = (code_buf[cb][p0_word] >> p0_pos) & 1;

            int s0 = (syndrome[cb][0 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int s1 = (syndrome[cb][1 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int s3 = (syndrome[cb][3 * words_per_Z + z / 32] >> (z % 32)) & 1;

            // p1
            {
                int p1_bit = s0 ^ p0_shifted;
                warp_bits = __ballot_sync(warp_mask, p1_bit);
                if (lane_id == 0) code_buf[cb][(Kb + 1) * words_per_Z + warp_id] = warp_bits;
            }
            __syncthreads();

            // p2
            {
                int p1_z = (code_buf[cb][(Kb + 1) * words_per_Z + z / 32] >> (z % 32)) & 1;
                int p2_bit = s1 ^ p1_z;
                warp_bits = __ballot_sync(warp_mask, p2_bit);
                if (lane_id == 0) code_buf[cb][(Kb + 2) * words_per_Z + warp_id] = warp_bits;
            }
            __syncthreads();

            // p3
            {
                int p3_bit = s3 ^ p0_shifted;
                warp_bits = __ballot_sync(warp_mask, p3_bit);
                if (lane_id == 0) code_buf[cb][(Kb + 3) * words_per_Z + warp_id] = warp_bits;
            }
        }
    }
    __syncthreads();

    // =========================================================================
    // Step 4: Extended parity (rows 4 to M-1) - all 4 CBs with ILP
    // =========================================================================
    for (int row = 4; row < M; row++) {
        int row_start = d_row_ptr[row];
        int row_end = d_row_ptr[row + 1];

        int parity_bits[MULTI_CB_COUNT] = {0, 0, 0, 0};
        int parity_col = -1;

        for (int e = row_start; e < row_end; e++) {
            int col = d_col_idx[e];
            int shift = d_shifts[e];
            if (shift < 0) continue;

            if (col >= Kb + 4) {
                parity_col = col;
            } else {
                int src_z = (z + shift) % Z;
                int word_idx = col * words_per_Z + src_z / 32;
                int bit_pos = src_z % 32;

                #pragma unroll
                for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                    if (cb < valid_cbs) {
                        parity_bits[cb] ^= (code_buf[cb][word_idx] >> bit_pos) & 1;
                    }
                }
            }
        }

        // Store parity for all 4 CBs (no syncthreads needed - rows are independent)
        if (parity_col >= 0) {
            #pragma unroll
            for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                if (cb < valid_cbs) {
                    uint32_t warp_bits = __ballot_sync(warp_mask, parity_bits[cb]);
                    if (lane_id == 0) {
                        code_buf[cb][parity_col * words_per_Z + warp_id] = warp_bits;
                    }
                }
            }
        }
    }
    __syncthreads();

    // =========================================================================
    // Step 5: Output all 4 CBs with MSB-first byte reordering
    // =========================================================================
    auto byte_reverse_bits = [](uint32_t x) -> uint32_t {
        x = ((x & 0x55555555u) << 1) | ((x >> 1) & 0x55555555u);
        x = ((x & 0x33333333u) << 2) | ((x >> 2) & 0x33333333u);
        x = ((x & 0x0F0F0F0Fu) << 4) | ((x >> 4) & 0x0F0F0F0Fu);
        return x;
    };

    if ((Z % 32) == 0) {
        // Fast path: warp-cooperative writes for all 4 CBs
        for (int col = 0; col < N; col++) {
            #pragma unroll
            for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                if (cb < valid_cbs) {
                    int src_word = col * words_per_Z + warp_id;
                    int bit = (code_buf[cb][src_word] >> lane_id) & 1;
                    uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, bit);
                    warp_bits = byte_reverse_bits(warp_bits);

                    if (lane_id == 0) {
                        int dst_word = col * words_per_Z + warp_id;
                        if (dst_word < output_stride) {
                            output[cb][dst_word] = warp_bits;
                        }
                    }
                }
            }
        }
    } else {
        // Slow path: atomicOr for non-aligned Z
        for (int col = 0; col < N; col++) {
            #pragma unroll
            for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                if (cb < valid_cbs) {
                    int src_word = col * words_per_Z + z / 32;
                    int src_bit = z % 32;
                    int bit = (code_buf[cb][src_word] >> src_bit) & 1;

                    int dst_idx = col * Z + z;
                    int dst_word = dst_idx / 32;
                    int bit_in_word = dst_idx % 32;
                    int byte_in_word = bit_in_word / 8;
                    int bit_in_byte = 7 - (bit_in_word % 8);
                    int dst_bit = byte_in_word * 8 + bit_in_byte;

                    if (dst_word < output_stride && bit) {
                        atomicOr(&output[cb][dst_word], 1u << dst_bit);
                    }
                }
            }
        }
    }
}

/**
 * @brief Multi-CB LDPC encoder with funnel shift optimization
 *
 * Uses __funnelshift_r intrinsic for efficient cyclic bit rotation.
 * This eliminates expensive modulo operations in the inner loop.
 * Specialized for Z=384 (most common case for high-throughput).
 *
 * Launch bounds tuning:
 * - 384 threads (Z=384) with 3 blocks/SM = 1152 threads/SM (~56% occupancy)
 * - Tested on GH200: 3 blocks/SM gives 72.7 Gbps (best)
 * - 2 blocks/SM: 65.2 Gbps, 4 blocks/SM: 72.0 Gbps
 * - Shared memory: ~22KB/block × 3 = 66KB/SM (well under 227KB limit)
 * - Works across: GH200 (132 SMs), H100 (114-132 SMs), A100 (80-108 SMs)
 */
__global__ void __launch_bounds__(384, 3)
ldpc_encode_multi_cb_funnel_kernel(
    const uint32_t* __restrict__ d_input,
    uint32_t* __restrict__ d_output,
    const int* __restrict__ d_row_ptr,
    const int8_t* __restrict__ d_col_idx,
    const int16_t* __restrict__ d_shifts,
    int Z,
    int Kb,
    int N,
    int M,
    int input_stride,
    int output_stride,
    int num_codewords,
    int base_graph,
    int lifting_set_idx
) {
    extern __shared__ uint32_t smem[];

    const int cb_base = blockIdx.x * MULTI_CB_COUNT;
    const int valid_cbs = min(MULTI_CB_COUNT, num_codewords - cb_base);
    if (valid_cbs <= 0) return;

    const int z = threadIdx.x;
    if (z >= Z) return;

    const int lane_id = z % 32;
    const int warp_id = z / 32;
    const int num_full_warps = Z / 32;
    const int partial_warp_size = Z % 32;
    const bool is_partial_warp = (warp_id == num_full_warps) && (partial_warp_size > 0);
    const uint32_t warp_mask = is_partial_warp ? ((1u << partial_warp_size) - 1) : 0xFFFFFFFF;

    const int words_per_Z = (Z + 31) / 32;
    const int code_buf_size = N * words_per_Z;
    const int syndrome_size = M * words_per_Z;

    uint32_t* code_buf[MULTI_CB_COUNT];
    uint32_t* syndrome[MULTI_CB_COUNT];

    for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
        code_buf[cb] = smem + cb * code_buf_size;
        syndrome[cb] = smem + MULTI_CB_COUNT * code_buf_size + cb * syndrome_size;
    }

    const uint32_t* input[MULTI_CB_COUNT];
    uint32_t* output[MULTI_CB_COUNT];
    for (int cb = 0; cb < valid_cbs; cb++) {
        input[cb] = d_input + (cb_base + cb) * input_stride;
        output[cb] = d_output + (cb_base + cb) * output_stride;
    }

    // Clear shared memory
    for (int i = z; i < MULTI_CB_COUNT * code_buf_size; i += Z) {
        smem[i] = 0;
    }
    for (int i = z; i < MULTI_CB_COUNT * syndrome_size; i += Z) {
        smem[MULTI_CB_COUNT * code_buf_size + i] = 0;
    }
    __syncthreads();

    // Step 0: Load systematic bits (same as before)
    for (int col = 0; col < Kb && col < N; col++) {
        int bits[MULTI_CB_COUNT] = {0, 0, 0, 0};

        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                int input_bit_idx = col * Z + z;
                int input_word_idx = input_bit_idx / 32;
                int bit_in_word = input_bit_idx % 32;
                int byte_in_word = bit_in_word / 8;
                int bit_in_byte = 7 - (bit_in_word % 8);
                int input_bit_pos = byte_in_word * 8 + bit_in_byte;

                if (input_word_idx < input_stride) {
                    uint32_t word = input[cb][input_word_idx];
                    bits[cb] = (word >> input_bit_pos) & 1;
                }
            }
        }

        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                uint32_t warp_bits = __ballot_sync(warp_mask, bits[cb]);
                if (lane_id == 0) {
                    code_buf[cb][col * words_per_Z + warp_id] = warp_bits;
                }
            }
        }
    }
    __syncthreads();

    // Step 1: Compute syndromes using FUNNEL SHIFT + LOOP UNROLLING (2x)
    // Aerial SDK technique: process 2 columns per iteration with dual accumulators
    for (int row = 0; row < 4 && row < M; row++) {
        int row_start = d_row_ptr[row];
        int row_end = d_row_ptr[row + 1];
        int deg = row_end - row_start;

        // Dual accumulators for better ILP
        int syn_bits0[MULTI_CB_COUNT] = {0, 0, 0, 0};
        int syn_bits1[MULTI_CB_COUNT] = {0, 0, 0, 0};

        // Process pairs of columns (unroll by 2)
        int deg_even = 2 * (deg / 2);
        for (int i = 0; i < deg_even; i += 2) {
            int e0 = row_start + i;
            int e1 = row_start + i + 1;

            int col0 = d_col_idx[e0];
            int col1 = d_col_idx[e1];
            int shift0 = d_shifts[e0];
            int shift1 = d_shifts[e1];

            // Process column 0
            if (col0 < Kb && shift0 >= 0) {
                #pragma unroll
                for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                    if (cb < valid_cbs) {
                        const uint32_t* col_data = &code_buf[cb][col0 * words_per_Z];
                        uint32_t rotated = funnel_rotated_word<12>(col_data, warp_id, shift0);
                        int bit = (rotated >> lane_id) & 1;
                        syn_bits0[cb] ^= bit;
                    }
                }
            }

            // Process column 1 (independent from column 0 - ILP)
            if (col1 < Kb && shift1 >= 0) {
                #pragma unroll
                for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                    if (cb < valid_cbs) {
                        const uint32_t* col_data = &code_buf[cb][col1 * words_per_Z];
                        uint32_t rotated = funnel_rotated_word<12>(col_data, warp_id, shift1);
                        int bit = (rotated >> lane_id) & 1;
                        syn_bits1[cb] ^= bit;
                    }
                }
            }
        }

        // Handle odd column if degree is odd
        if (deg & 1) {
            int e = row_start + deg - 1;
            int col = d_col_idx[e];
            int shift = d_shifts[e];

            if (col < Kb && shift >= 0) {
                #pragma unroll
                for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                    if (cb < valid_cbs) {
                        const uint32_t* col_data = &code_buf[cb][col * words_per_Z];
                        uint32_t rotated = funnel_rotated_word<12>(col_data, warp_id, shift);
                        int bit = (rotated >> lane_id) & 1;
                        syn_bits0[cb] ^= bit;
                    }
                }
            }
        }

        // Merge dual accumulators and store
        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                int final_bit = syn_bits0[cb] ^ syn_bits1[cb];
                uint32_t warp_bits = __ballot_sync(warp_mask, final_bit);
                if (lane_id == 0) {
                    syndrome[cb][row * words_per_Z + warp_id] = warp_bits;
                }
            }
        }
    }
    __syncthreads();

    // Step 2 & 3: Compute parity bits p0-p3 (BG1)
    if (base_graph == 1) {
        bool is_i6 = (lifting_set_idx == 6);

        int p0_bits[MULTI_CB_COUNT] = {0, 0, 0, 0};

        if (is_i6) {
            int p0_syn_shift = 105 % Z;
            int src_z = (z - p0_syn_shift + Z) % Z;
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + src_z / 32;
                int syn_pos = src_z % 32;
                #pragma unroll
                for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                    if (cb < valid_cbs) {
                        p0_bits[cb] ^= (syndrome[cb][syn_word] >> syn_pos) & 1;
                    }
                }
            }
        } else {
            for (int row = 0; row < 4 && row < M; row++) {
                int syn_word = row * words_per_Z + z / 32;
                int syn_pos = z % 32;
                #pragma unroll
                for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                    if (cb < valid_cbs) {
                        p0_bits[cb] ^= (syndrome[cb][syn_word] >> syn_pos) & 1;
                    }
                }
            }
        }

        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                uint32_t warp_bits = __ballot_sync(warp_mask, p0_bits[cb]);
                if (lane_id == 0) {
                    code_buf[cb][Kb * words_per_Z + warp_id] = warp_bits;
                }
            }
        }
        __syncthreads();

        int p0_shift = is_i6 ? 0 : 1;
        int p0_src_z = (z + p0_shift) % Z;
        int p0_word_idx = Kb * words_per_Z + p0_src_z / 32;
        int p0_pos = p0_src_z % 32;

        int p0_shifted[MULTI_CB_COUNT];
        int syn0[MULTI_CB_COUNT], syn2[MULTI_CB_COUNT], syn3[MULTI_CB_COUNT];

        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                p0_shifted[cb] = (code_buf[cb][p0_word_idx] >> p0_pos) & 1;
                syn0[cb] = (syndrome[cb][0 * words_per_Z + z / 32] >> (z % 32)) & 1;
                syn2[cb] = (syndrome[cb][2 * words_per_Z + z / 32] >> (z % 32)) & 1;
                syn3[cb] = (syndrome[cb][3 * words_per_Z + z / 32] >> (z % 32)) & 1;
            }
        }

        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                int p1_bit = syn0[cb] ^ p0_shifted[cb];
                uint32_t warp_bits = __ballot_sync(warp_mask, p1_bit);
                if (lane_id == 0) {
                    code_buf[cb][(Kb + 1) * words_per_Z + warp_id] = warp_bits;
                }
            }
        }

        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                int p3_bit = syn3[cb] ^ p0_shifted[cb];
                uint32_t warp_bits = __ballot_sync(warp_mask, p3_bit);
                if (lane_id == 0) {
                    code_buf[cb][(Kb + 3) * words_per_Z + warp_id] = warp_bits;
                }
            }
        }
        __syncthreads();

        #pragma unroll
        for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
            if (cb < valid_cbs) {
                int p3_z = (code_buf[cb][(Kb + 3) * words_per_Z + z / 32] >> (z % 32)) & 1;
                int p2_bit = syn2[cb] ^ p3_z;
                uint32_t warp_bits = __ballot_sync(warp_mask, p2_bit);
                if (lane_id == 0) {
                    code_buf[cb][(Kb + 2) * words_per_Z + warp_id] = warp_bits;
                }
            }
        }
    } else {
        // BG2 fallback (same as before)
        bool is_i3_i7 = (lifting_set_idx == 3 || lifting_set_idx == 7);

        for (int cb = 0; cb < valid_cbs; cb++) {
            int p0_bit = 0;
            if (is_i3_i7) {
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + z / 32;
                    int syn_pos = z % 32;
                    p0_bit ^= (syndrome[cb][syn_word] >> syn_pos) & 1;
                }
            } else {
                int src_z = (z - 1 + Z) % Z;
                for (int row = 0; row < 4 && row < M; row++) {
                    int syn_word = row * words_per_Z + src_z / 32;
                    int syn_pos = src_z % 32;
                    p0_bit ^= (syndrome[cb][syn_word] >> syn_pos) & 1;
                }
            }

            uint32_t warp_bits = __ballot_sync(warp_mask, p0_bit);
            if (lane_id == 0) code_buf[cb][Kb * words_per_Z + warp_id] = warp_bits;
            __syncthreads();

            int p0_src_z = is_i3_i7 ? ((z + 1) % Z) : z;
            int p0_word = Kb * words_per_Z + p0_src_z / 32;
            int p0_pos = p0_src_z % 32;
            int p0_shifted = (code_buf[cb][p0_word] >> p0_pos) & 1;

            int s0 = (syndrome[cb][0 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int s1 = (syndrome[cb][1 * words_per_Z + z / 32] >> (z % 32)) & 1;
            int s3 = (syndrome[cb][3 * words_per_Z + z / 32] >> (z % 32)) & 1;

            {
                int p1_bit = s0 ^ p0_shifted;
                warp_bits = __ballot_sync(warp_mask, p1_bit);
                if (lane_id == 0) code_buf[cb][(Kb + 1) * words_per_Z + warp_id] = warp_bits;
            }
            __syncthreads();

            {
                int p1_z = (code_buf[cb][(Kb + 1) * words_per_Z + z / 32] >> (z % 32)) & 1;
                int p2_bit = s1 ^ p1_z;
                warp_bits = __ballot_sync(warp_mask, p2_bit);
                if (lane_id == 0) code_buf[cb][(Kb + 2) * words_per_Z + warp_id] = warp_bits;
            }
            __syncthreads();

            {
                int p3_bit = s3 ^ p0_shifted;
                warp_bits = __ballot_sync(warp_mask, p3_bit);
                if (lane_id == 0) code_buf[cb][(Kb + 3) * words_per_Z + warp_id] = warp_bits;
            }
        }
    }
    __syncthreads();

    // Step 4: Extended parity using FUNNEL SHIFT + LOOP UNROLLING (2x)
    for (int row = 4; row < M; row++) {
        int row_start = d_row_ptr[row];
        int row_end = d_row_ptr[row + 1];
        int deg = row_end - row_start;

        // Dual accumulators for ILP
        int parity_bits0[MULTI_CB_COUNT] = {0, 0, 0, 0};
        int parity_bits1[MULTI_CB_COUNT] = {0, 0, 0, 0};
        int parity_col = -1;

        // Process pairs of entries (unroll by 2)
        int deg_even = 2 * (deg / 2);
        for (int i = 0; i < deg_even; i += 2) {
            int e0 = row_start + i;
            int e1 = row_start + i + 1;

            int col0 = d_col_idx[e0];
            int col1 = d_col_idx[e1];
            int shift0 = d_shifts[e0];
            int shift1 = d_shifts[e1];

            // Entry 0
            if (shift0 >= 0) {
                if (col0 >= Kb + 4) {
                    parity_col = col0;
                } else {
                    #pragma unroll
                    for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                        if (cb < valid_cbs) {
                            const uint32_t* col_data = &code_buf[cb][col0 * words_per_Z];
                            uint32_t rotated = funnel_rotated_word<12>(col_data, warp_id, shift0);
                            int bit = (rotated >> lane_id) & 1;
                            parity_bits0[cb] ^= bit;
                        }
                    }
                }
            }

            // Entry 1 (independent - ILP)
            if (shift1 >= 0) {
                if (col1 >= Kb + 4) {
                    parity_col = col1;
                } else {
                    #pragma unroll
                    for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                        if (cb < valid_cbs) {
                            const uint32_t* col_data = &code_buf[cb][col1 * words_per_Z];
                            uint32_t rotated = funnel_rotated_word<12>(col_data, warp_id, shift1);
                            int bit = (rotated >> lane_id) & 1;
                            parity_bits1[cb] ^= bit;
                        }
                    }
                }
            }
        }

        // Handle odd entry
        if (deg & 1) {
            int e = row_start + deg - 1;
            int col = d_col_idx[e];
            int shift = d_shifts[e];

            if (shift >= 0) {
                if (col >= Kb + 4) {
                    parity_col = col;
                } else {
                    #pragma unroll
                    for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                        if (cb < valid_cbs) {
                            const uint32_t* col_data = &code_buf[cb][col * words_per_Z];
                            uint32_t rotated = funnel_rotated_word<12>(col_data, warp_id, shift);
                            int bit = (rotated >> lane_id) & 1;
                            parity_bits0[cb] ^= bit;
                        }
                    }
                }
            }
        }

        // Merge accumulators and store parity
        if (parity_col >= 0) {
            #pragma unroll
            for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                if (cb < valid_cbs) {
                    int final_bit = parity_bits0[cb] ^ parity_bits1[cb];
                    uint32_t warp_bits = __ballot_sync(warp_mask, final_bit);
                    if (lane_id == 0) {
                        code_buf[cb][parity_col * words_per_Z + warp_id] = warp_bits;
                    }
                }
            }
        }
    }
    __syncthreads();

    // Step 5: Output with MSB-first byte reordering
    auto byte_reverse_bits = [](uint32_t x) -> uint32_t {
        x = ((x & 0x55555555u) << 1) | ((x >> 1) & 0x55555555u);
        x = ((x & 0x33333333u) << 2) | ((x >> 2) & 0x33333333u);
        x = ((x & 0x0F0F0F0Fu) << 4) | ((x >> 4) & 0x0F0F0F0Fu);
        return x;
    };

    if ((Z % 32) == 0) {
        for (int col = 0; col < N; col++) {
            #pragma unroll
            for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                if (cb < valid_cbs) {
                    int src_word = col * words_per_Z + warp_id;
                    int bit = (code_buf[cb][src_word] >> lane_id) & 1;
                    uint32_t warp_bits = __ballot_sync(0xFFFFFFFF, bit);
                    warp_bits = byte_reverse_bits(warp_bits);

                    if (lane_id == 0) {
                        int dst_word = col * words_per_Z + warp_id;
                        if (dst_word < output_stride) {
                            output[cb][dst_word] = warp_bits;
                        }
                    }
                }
            }
        }
    } else {
        for (int col = 0; col < N; col++) {
            #pragma unroll
            for (int cb = 0; cb < MULTI_CB_COUNT; cb++) {
                if (cb < valid_cbs) {
                    int src_word = col * words_per_Z + z / 32;
                    int src_bit = z % 32;
                    int bit = (code_buf[cb][src_word] >> src_bit) & 1;

                    int dst_idx = col * Z + z;
                    int dst_word = dst_idx / 32;
                    int bit_in_word = dst_idx % 32;
                    int byte_in_word = bit_in_word / 8;
                    int bit_in_byte = 7 - (bit_in_word % 8);
                    int dst_bit = byte_in_word * 8 + bit_in_byte;

                    if (dst_word < output_stride && bit) {
                        atomicOr(&output[cb][dst_word], 1u << dst_bit);
                    }
                }
            }
        }
    }
}

nr_ldpc_status_t ldpc_encoder_encode(
    ldpc_encoder_handle_t handle,
    const uint32_t* d_input,
    uint32_t* d_output,
    cudaStream_t stream
) {
    return ldpc_encoder_encode_batch(handle, d_input, d_output, 1, stream);
}

nr_ldpc_status_t ldpc_encoder_encode_batch(
    ldpc_encoder_handle_t handle,
    const uint32_t* d_input,
    uint32_t* d_output,
    int num_codewords,
    cudaStream_t stream
) {
    FlexibleLdpcEncoder* enc = reinterpret_cast<FlexibleLdpcEncoder*>(handle);
    if (!enc || !d_input || !d_output || num_codewords <= 0) {
        return NR_LDPC_ERROR_INVALID_CONFIG;
    }

    int words_per_Z = (enc->Z + 31) / 32;

    // =========================================================================
    // PHASE 2 OPTIMIZATION: Avoid LDPC output buffer memset
    // =========================================================================
    // Warp-aligned Z values directly write whole output words with warp ballots.
    // Non-aligned Z values now pack one flat output word per thread from shared
    // memory instead of using per-bit atomicOr. Both paths fully overwrite the
    // encoded output, including partial tail words, so no memset is needed.
    // =========================================================================
    bool needs_memset = false;
    if (needs_memset) {
        cudaMemsetAsync(d_output, 0, num_codewords * enc->output_words * sizeof(uint32_t), stream);
    }

    // Platform-adaptive kernel selection
    //
    // Multi-CB kernel (4 CB/block): Higher ILP, fewer blocks, better for large batches
    // Warp-cooperative (1 CB/block): More blocks, better SM occupancy for small batches
    //
    // Heuristic: Use multi-CB when the resulting blocks provide sufficient work
    // For small GPUs (16-48 SMs), multi-CB is better even for small batches due to ILP
    // For large GPUs (100+ SMs), 4× ILP compensates for lower block count
    //
    // Decision: Use multi-CB when Z is warp-aligned and batch >= 4
    // The 4× ILP is almost always beneficial regardless of SM count
    int multi_cb_blocks = (num_codewords + MULTI_CB_COUNT - 1) / MULTI_CB_COUNT;
    int max_concurrent_blocks = enc->sm_count * enc->max_blocks_per_sm;

    // For Z=384, one CB per block exposes more independent blocks and is
    // substantially faster for the current PDSCH full-path latency target than
    // the 4-CB funnel kernel. Keep the multi-CB path for other warp-aligned Z.
    bool use_multi_cb = (enc->Z % 32 == 0) && (enc->Z != 384) && (num_codewords >= MULTI_CB_COUNT);

    // =========================================================================
    // PHASE 2 OPTIMIZATION: More aggressive multi-CB kernel threshold
    // =========================================================================
    // Original: <25% SM utilization AND batch < 16 → use warp-coop
    // New:      <12.5% SM utilization AND batch < 8 → use warp-coop
    //
    // This enables multi-CB kernel for 4-15 CB batches on large GPUs, providing
    // better ILP (4× work per block) even at lower SM utilization.
    // The 4× ILP from processing 4 CBs per block usually outweighs the benefit
    // of having more blocks for occupancy.
    // =========================================================================
    if (use_multi_cb && multi_cb_blocks * 8 < max_concurrent_blocks && num_codewords < 8) {
        use_multi_cb = false;
    }

    // Use funnel shift kernel specifically for Z=384 (12 words per column)
    bool use_funnel = (enc->Z == 384) && use_multi_cb;

    if (use_funnel) {
        // Funnel shift optimized kernel for Z=384
        // Uses __funnelshift_r for efficient cyclic bit rotation
        size_t smem_size = MULTI_CB_COUNT * (enc->N * words_per_Z + enc->M * words_per_Z) * sizeof(uint32_t);
        int num_blocks = (num_codewords + MULTI_CB_COUNT - 1) / MULTI_CB_COUNT;

        ldpc_encode_multi_cb_funnel_kernel<<<num_blocks, enc->Z, smem_size, stream>>>(
            d_input, d_output,
            enc->d_row_ptr, enc->d_col_idx, enc->d_shifts,
            enc->Z, enc->Kb, enc->N, enc->M,
            enc->input_words, enc->output_words,
            num_codewords,
            enc->base_graph, enc->lifting_set_idx
        );
    } else if (use_multi_cb) {
        // Multi-CB kernel: each block processes 4 CBs
        // Shared memory: 4 code buffers + 4 syndrome arrays
        size_t smem_size = MULTI_CB_COUNT * (enc->N * words_per_Z + enc->M * words_per_Z) * sizeof(uint32_t);

        // Number of blocks = ceil(num_codewords / 4)
        int num_blocks = (num_codewords + MULTI_CB_COUNT - 1) / MULTI_CB_COUNT;

        ldpc_encode_multi_cb_kernel<<<num_blocks, enc->Z, smem_size, stream>>>(
            d_input, d_output,
            enc->d_row_ptr, enc->d_col_idx, enc->d_shifts,
            enc->Z, enc->Kb, enc->N, enc->M,
            enc->input_words, enc->output_words,
            num_codewords,
            enc->base_graph, enc->lifting_set_idx
        );
    } else if (enc->Z == 384) {
        // =====================================================================
        // PHASE 2 OPTIMIZATION: Specialized Z=384 warp-cooperative kernel
        // =====================================================================
        // Uses cyclic_add_384/cyclic_sub_384 helpers instead of modulo,
        // saving ~2 cycles per rotation (5-8 µs/CB improvement)
        // =====================================================================
        size_t smem_size = (enc->N * words_per_Z + enc->M * words_per_Z) * sizeof(uint32_t);

        ldpc_encode_warp_coop_z384_kernel<<<num_codewords, 384, smem_size, stream>>>(
            d_input, d_output,
            enc->d_row_ptr, enc->d_col_idx, enc->d_shifts,
            enc->Kb, enc->N, enc->M,
            enc->input_words, enc->output_words,
            num_codewords,
            enc->base_graph, enc->lifting_set_idx
        );
    } else if (enc->Z == 192 || enc->Z == 208 || enc->Z == 224 ||
               enc->Z == 240 || enc->Z == 320 || enc->Z == 352) {
        // Fixed-Z instantiations cover the common 1-layer PDSCH cases.
        // They keep the generic algorithm but let NVCC constant-fold Z,
        // words_per_Z, wrap checks, and partial-warp handling.
        size_t smem_size = (enc->N * words_per_Z + enc->M * words_per_Z) * sizeof(uint32_t);

        if (enc->Z == 192) {
            ldpc_encode_warp_cooperative_kernel<192><<<num_codewords, 192, smem_size, stream>>>(
                d_input, d_output,
                enc->d_row_ptr, enc->d_col_idx, enc->d_shifts,
                enc->Z, enc->Kb, enc->N, enc->M,
                enc->input_words, enc->output_words,
                num_codewords,
                enc->base_graph, enc->lifting_set_idx
            );
        } else if (enc->Z == 208) {
            ldpc_encode_warp_cooperative_kernel<208><<<num_codewords, 208, smem_size, stream>>>(
                d_input, d_output,
                enc->d_row_ptr, enc->d_col_idx, enc->d_shifts,
                enc->Z, enc->Kb, enc->N, enc->M,
                enc->input_words, enc->output_words,
                num_codewords,
                enc->base_graph, enc->lifting_set_idx
            );
        } else if (enc->Z == 224) {
            ldpc_encode_warp_cooperative_kernel<224><<<num_codewords, 224, smem_size, stream>>>(
                d_input, d_output,
                enc->d_row_ptr, enc->d_col_idx, enc->d_shifts,
                enc->Z, enc->Kb, enc->N, enc->M,
                enc->input_words, enc->output_words,
                num_codewords,
                enc->base_graph, enc->lifting_set_idx
            );
        } else if (enc->Z == 240) {
            static const bool use_z240_row4 =
                ldpc_encoder_env_flag_enabled("OCUDU_LDPC_Z240_ROW4", true);
            if (use_z240_row4) {
                ldpc_encode_warp_coop_z240_row4_kernel<<<num_codewords, 1024, smem_size, stream>>>(
                    d_input, d_output,
                    enc->d_row_ptr, enc->d_col_idx, enc->d_shifts,
                    enc->Kb, enc->N, enc->M,
                    enc->input_words, enc->output_words,
                    num_codewords,
                    enc->base_graph, enc->lifting_set_idx
                );
            } else {
                ldpc_encode_warp_cooperative_kernel<240><<<num_codewords, 240, smem_size, stream>>>(
                    d_input, d_output,
                    enc->d_row_ptr, enc->d_col_idx, enc->d_shifts,
                    enc->Z, enc->Kb, enc->N, enc->M,
                    enc->input_words, enc->output_words,
                    num_codewords,
                    enc->base_graph, enc->lifting_set_idx
                );
            }
        } else if (enc->Z == 320) {
            ldpc_encode_warp_cooperative_kernel<320><<<num_codewords, 320, smem_size, stream>>>(
                d_input, d_output,
                enc->d_row_ptr, enc->d_col_idx, enc->d_shifts,
                enc->Z, enc->Kb, enc->N, enc->M,
                enc->input_words, enc->output_words,
                num_codewords,
                enc->base_graph, enc->lifting_set_idx
            );
        } else {
            ldpc_encode_warp_cooperative_kernel<352><<<num_codewords, 352, smem_size, stream>>>(
                d_input, d_output,
                enc->d_row_ptr, enc->d_col_idx, enc->d_shifts,
                enc->Z, enc->Kb, enc->N, enc->M,
                enc->input_words, enc->output_words,
                num_codewords,
                enc->base_graph, enc->lifting_set_idx
            );
        }
    } else {
        // Warp-cooperative kernel for small batches or non-aligned Z
        size_t smem_size = (enc->N * words_per_Z + enc->M * words_per_Z) * sizeof(uint32_t);

        ldpc_encode_warp_cooperative_kernel<0><<<num_codewords, enc->Z, smem_size, stream>>>(
            d_input, d_output,
            enc->d_row_ptr, enc->d_col_idx, enc->d_shifts,
            enc->Z, enc->Kb, enc->N, enc->M,
            enc->input_words, enc->output_words,
            num_codewords,
            enc->base_graph, enc->lifting_set_idx
        );
    }

    return NR_LDPC_SUCCESS;
}

void ldpc_encoder_destroy(ldpc_encoder_handle_t handle) {
    FlexibleLdpcEncoder* enc = reinterpret_cast<FlexibleLdpcEncoder*>(handle);
    if (enc) {
        if (enc->d_row_ptr) cudaFree(enc->d_row_ptr);
        if (enc->d_col_idx) cudaFree(enc->d_col_idx);
        if (enc->d_shifts) cudaFree(enc->d_shifts);
        delete enc;
    }
}

